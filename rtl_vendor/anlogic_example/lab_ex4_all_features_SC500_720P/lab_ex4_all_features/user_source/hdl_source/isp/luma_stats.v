// ============================================================================
//  luma_stats.v  ---  每帧亮度统计（P6 / AE 闭环的"眼睛"）
//
//  职责：旁路 awb 的输出，对每帧所有像素求
//      O_sum  : ΣY                （32 bit，720p 满幅 = 921600×255 = 235,008,000 < 2^32）
//      O_clip : Y >= CLIP_TH 的像素数（高光保护用）
//      O_dark : Y <= DARK_TH 的像素数（死黑检测用）
//      O_dark : Y <= DARK_TH 的像素数（死黑检测用）
//  并在帧末锁存 + 翻转一个跨域握手标志。
//  ⚠ **平均亮度不在这里算**（曾经在这里，布线后成了本域最差路径，见 §3 的实测记录）。
//  并在帧末锁存 + 翻转一个跨域握手标志。
//
//  ---------------------------------------------------------------------------
//  ★ 为什么放在 ISP 域（`axi4s_video_aclk` = MIPI_RX_BYTE_CLK ≈ 60 MHz）
//  ---------------------------------------------------------------------------
//  P5 已经用实测数字定过这件事（见 target_detect_96.v 头注释）：
//      MIPI_RX_BYTE_CLK  59.995 MHz 需求，实测 77.954 MHz ⇒ +29.9%
//      HDMI_PIXEL_CLK    75.002 MHz 需求，实测 76.752 MHz ⇒ **+2.3%（最紧）**
//  亮度统计要在**像素率**上跑（每拍 4 个像素求和），放 HDMI 域会直接把它压垮。
//  ⇒ 统计在 ISP 域做，每帧只把几个**标量**送到 24 MHz 的 ae_ctrl。
//
//  ---------------------------------------------------------------------------
//  ★★ 帧边界：**纯拍数自计时**，不碰 tuser / tlast（本项目铁律四）
//  ---------------------------------------------------------------------------
//  `awb.v` 的输出口上：
//      awb.v:370  assign O_tuser = I_tuser;                          // 组合直通
//      awb.v:371  assign O_tvalid = valid_d2;                        // 有流水延迟
//      awb.v:369  assign O_tlast = (valid_d1==0)&&(valid_d2==1);     // 是 valid 上升沿！
//  ⇒ `tuser` 到达那一拍落在帧间消隐期（tvalid=0），以 `tvalid && tuser` 做帧结算
//    **永不成立**；`tlast` 根本不是行尾。P5 上板"永远 NONE"就是这么来的
//    （模块级仿真全绿也查不出，因为激励是照着教科书时序写的）。
//  ⇒ 本模块只数**有效拍**：
//        每行 1280/4 = 320 拍，每帧 720 行 ⇒ 230,400 拍，最后一拍编号 230,399
//    （上板已由 P5 的诊断行验证：`B E0` ⇒ 230399>>10 = 224 = 0xE0 ✓）
//
//  ---------------------------------------------------------------------------
//  ★ 零 DSP、零除法（本项目铁律三）
//  ---------------------------------------------------------------------------
//  亮度系数与 `gray_binary_96` **同一个式子**（保证"AE 看到的亮度"就是
//  "灰度模式看到的亮度"，不会出现两套亮度打架）：
//      Y = (77R + 150G + 29B) >> 8
//  系数分解（严格等式，全部移位加法，绝不用 `*`）：
//      77  = 64+8+4+1        150 = 128+16+4+2        29 = 32−4+1
//  求和上限 = 255×(77+150+29) = 255×256 = 65280 < 65536 ⇒ 16 位中间量不会溢出。
//
//  ★ 平均亮度的算法（**只在帧末算 1 次，不在像素率上**）
//      921600 = 900 × 1024  ⇒  avg = (sum >> 10) / 900
//      把 /900 换成"乘倒数再右移"：avg ≈ ((sum>>10) × 18642) >> 24
//        18642 = 16384+2048+128+64+16+2（移位加法）
//      取整验证：sum=921600×128 ⇒ 127.99 截断为 **128** ✓（若取 18641 会得 127，偏 1）
//      ⇒ 8 位平均亮度，误差 ≤ 1 LSB，足够 OSD 显示。
//      ⚠ 控制回路**不使用** avg —— 它直接拿 `sum` 和常量阈值比（见 ae_ctrl.v），
//        这样回路上根本没有除法器。
//
//  ---------------------------------------------------------------------------
//  ★ 跨域：准静态多比特 + 翻转标志（与 P5 同一套，已在板上验证过）
//  ---------------------------------------------------------------------------
//  数据每帧只变一次（帧末锁存），一帧内完全静止（≈16.7 ms）。
//  写侧在数据变化的同一拍翻 `O_tog`，读侧经 2 拍同步后才看到翻转 ——
//  此时距数据变化已过 2~3 个目的域周期，而数据还要再静止 ≈16.6 ms
//  ⇒ **捕获瞬间绝不会撞上数据跳变**（同步器与边沿捕获在 ae_ctrl.v 里）。
//  ⚠ 前提条件：若将来这些量变成"每拍都变"，必须改成乒乓（参考 frame_latency.v）。
// ============================================================================
`timescale 1ns/1ps

module luma_stats #(
    parameter integer IMG_WIDTH   = 1280,
    parameter integer IMG_HEIGHT  = 720,
    parameter integer PX_PER_BEAT = 4,          // awb 输出每拍 4 个像素（96 bit = 4×RGB888）
    parameter [7:0]   CLIP_TH     = 8'd250,     // 高光阈值（≥ 记为过曝）
    parameter [7:0]   DARK_TH     = 8'd8        // 暗部阈值（≤ 记为死黑）
)(
    input  wire        I_clk,
    input  wire        I_rst_n,

    // ---- 与 target_detect_96 同一个 tap 点：awb 的 96 bit 输出 ----
    input  wire [95:0] I_tdata,      // p0{R,G,B} p1{R,G,B} p2{R,G,B} p3{R,G,B}
    input  wire        I_tvalid,

    // ---- 每帧一组结果（帧末更新，帧内完全稳定）----
    output reg  [31:0] O_sum,        // ΣY（本帧）
    output reg  [19:0] O_clip,       // Y >= CLIP_TH 的像素数
    output reg  [19:0] O_dark,       // Y <= DARK_TH 的像素数
    output reg         O_frame_done, // 帧末单拍（同域观察用，如 testbench）
    output reg         O_tog         // ★ 跨域握手：每帧翻转一次（准静态多比特）
);

    // ================================================================
    // 0. 帧几何（全部由参数推导，不硬编码）
    // ================================================================
    localparam integer BEAT_PER_LINE  = IMG_WIDTH / PX_PER_BEAT;         // 320
    localparam integer LINE_PER_FRAME = IMG_HEIGHT;                      // 720
    localparam integer NBEAT          = BEAT_PER_LINE * LINE_PER_FRAME;  // 230400
    localparam integer LAST_BEAT      = NBEAT - 1;                       // 230399 = 0x383FF

    // ================================================================
    // 1. 亮度 Y = (77R + 150G + 29B) >> 8（纯移位加法，无 `*` ⇒ 不推断 DSP）
    // ================================================================
    function [15:0] luma77;
        input [7:0] r, g, b;
        reg [15:0] r16, g16, b16;
        reg [16:0] t;
        begin
            r16 = {8'd0, r};
            g16 = {8'd0, g};
            b16 = {8'd0, b};
            //  77 = 64+8+4+1   150 = 128+16+4+2   29 = 32−4+1
            t   = ({1'b0, r16} << 6) + ({1'b0, r16} << 3) + ({1'b0, r16} << 2) + {1'b0, r16}
                + ({1'b0, g16} << 7) + ({1'b0, g16} << 4) + ({1'b0, g16} << 2) + ({1'b0, g16} << 1)
                + ({1'b0, b16} << 5) - ({1'b0, b16} << 2) + {1'b0, b16};
            luma77 = t[15:8];     // 上限 65280 ⇒ 高位恒 0，安全
        end
    endfunction

    // ---- 本拍 4 个像素的 R/G/B ----
    wire [7:0] p0_r = I_tdata[95:88], p0_g = I_tdata[87:80], p0_b = I_tdata[79:72];
    wire [7:0] p1_r = I_tdata[71:64], p1_g = I_tdata[63:56], p1_b = I_tdata[55:48];
    wire [7:0] p2_r = I_tdata[47:40], p2_g = I_tdata[39:32], p2_b = I_tdata[31:24];
    wire [7:0] p3_r = I_tdata[23:16], p3_g = I_tdata[15:8], p3_b = I_tdata[7:0];

    // ⚠ Verilog-2001 **不允许**对函数调用结果直接做位选（`f(...)[7:0]`），
    //   必须先进一个 wire 再切片 —— 这是本文件踩过的第一个语法坑。
    wire [15:0] y0_16 = luma77(p0_r, p0_g, p0_b);
    wire [15:0] y1_16 = luma77(p1_r, p1_g, p1_b);
    wire [15:0] y2_16 = luma77(p2_r, p2_g, p2_b);
    wire [15:0] y3_16 = luma77(p3_r, p3_g, p3_b);
    wire [7:0]  y0 = y0_16[7:0];
    wire [7:0]  y1 = y1_16[7:0];
    wire [7:0]  y2 = y2_16[7:0];
    wire [7:0]  y3 = y3_16[7:0];

    // ---- 本拍小计（树形归约，避免串行加法链）----
    wire [9:0]  y_beat   = {2'd0, y0} + {2'd0, y1} + {2'd0, y2} + {2'd0, y3};
    wire [2:0]  clip_beat = {2'd0, (y0 >= CLIP_TH)} + {2'd0, (y1 >= CLIP_TH)}
                          + {2'd0, (y2 >= CLIP_TH)} + {2'd0, (y3 >= CLIP_TH)};
    wire [2:0]  dark_beat = {2'd0, (y0 <= DARK_TH)} + {2'd0, (y1 <= DARK_TH)}
                          + {2'd0, (y2 <= DARK_TH)} + {2'd0, (y3 <= DARK_TH)};

    // ================================================================
    // 2. 帧累加器 + 拍计数（★ 只用 I_tvalid 计拍，不看 tuser/tlast）
    // ================================================================
    reg [17:0] S_beat;      // 0 .. 230399
    reg [31:0] S_sum;
    reg [19:0] S_clip;
    reg [19:0] S_dark;

    // 含本拍的下一状态（帧末锁存用，避免"少算最后一拍"）
    wire [31:0] w_sum_nxt  = S_sum  + {22'd0, y_beat};
    wire [19:0] w_clip_nxt = S_clip + {17'd0, clip_beat};
    wire [19:0] w_dark_nxt = S_dark + {17'd0, dark_beat};

    wire        w_frame_end = I_tvalid && (S_beat == LAST_BEAT);

    // ================================================================
    // 3. ★★ 这里**故意不在这里算平均亮度**（布线实测教训，2026-09-22）
    // ----------------------------------------------------------------------------
    //  第一版把 `avg = ((ΣY>>10) × 18642) >> 24` 也放在本模块里，并且用
    //  `w_sum_nxt`（含本拍的下一状态）当输入。布线后 TD 报出**本域最差路径**，
    //  端点就在本模块里，延迟 **16.307 ns > 16.668 ns 周期**（SWNS 只剩 +0.101 ns，
    //  本域 Fmax 从上一版的 77.954 MHz 掉到 **60.361 MHz，余量只剩 +0.6%**）。
    //
    //  路径实测构成（TD pr.timing，逐级可查）：
    //      luma77 的移位加法(第 112 行) → y_beat 四点求和(137) → 32 位累加(152)
    //      → 取 (ΣY>>10)(163) → **6 项移位加法树(165)**
    //  也就是说：**一个"每帧只用一次"的量，被串在了像素率路径的尾巴上**。
    //
    //  ⇒ 修法：平均亮度搬到 `ae_ctrl.v`（**24 MHz 域**，周期 42 ns）去算。
    //     它在那边只用于 OSD 显示，与死区判决毫无关系（判决用 ΣY 与常量阈值比），
    //     所以放在哪个域对功能没有任何影响，但对**时序**影响巨大。
    //     本模块的最差路径于是止于 32 位累加器（≈13.5 ns），余量回到 +3 ns 量级。
    //
    //  结论（值得写进铁律）：**"每帧只用一次"不等于"可以随便放"** ——
    //     只要它组合依赖像素率信号，它就在像素率路径上。
    // ================================================================

    // ================================================================
    // 4. 主时序
    // ================================================================
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            S_beat        <= 18'd0;
            S_sum         <= 32'd0;
            S_clip        <= 20'd0;
            S_dark        <= 20'd0;
            O_sum         <= 32'd0;
            O_clip        <= 20'd0;
            O_dark        <= 20'd0;
            O_frame_done  <= 1'b0;
            O_tog         <= 1'b0;
        end else begin
            O_frame_done <= 1'b0;                 // 默认单拍

            if (I_tvalid) begin
                if (w_frame_end) begin
                    // ---- 帧末：本拍**计入**后再锁存（共 230400 个有效拍）----
                    O_sum        <= w_sum_nxt;
                    O_clip       <= w_clip_nxt;
                    O_dark       <= w_dark_nxt;
                    O_frame_done <= 1'b1;
                    O_tog        <= ~O_tog;       // ★ 跨域握手边沿
                    S_sum        <= 32'd0;
                    S_clip       <= 20'd0;
                    S_dark       <= 20'd0;
                    S_beat       <= 18'd0;
                end else begin
                    S_sum  <= w_sum_nxt;
                    S_clip <= w_clip_nxt;
                    S_dark <= w_dark_nxt;
                    S_beat <= S_beat + 18'd1;
                end
            end
            // I_tvalid=0 时拍计数**冻结** ⇒ 帧边界仍由"有效拍数"唯一确定，
            // 行间空档不会把帧边界推偏（这正是 P5 证明可行的做法）。
        end
    end

endmodule
