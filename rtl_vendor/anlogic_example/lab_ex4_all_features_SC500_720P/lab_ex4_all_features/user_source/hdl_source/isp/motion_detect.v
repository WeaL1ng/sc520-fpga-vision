// ============================================================================
//  motion_detect.v  ---  运动目标检测（P7，进阶要求④"硬件运动目标检测 + 运动区域提示"）
//
//  官方原话：
//    进阶(4) "硬件运动目标检测（帧差法等），并给出运动区域的提示或计数"
//
//  设计规格见 `doc/analysis/P7设计-运动目标检测.md`。
//
//  ---------------------------------------------------------------------------
//  ★ 这个模块做什么（一句话）
//  ---------------------------------------------------------------------------
//   从 ISP 域"每拍 4 像素"的流里（与 luma_stats / target_detect_96 同一个 tap）
//   按 8×8 像素分块求亮度，和 **sigma-delta 背景模型** 比对得到"运动块"，
//   再做 **2×2 腐蚀** 去噪，最后给出：
//     · 本帧是否有运动              O_valid        （已含全局光照突变抑制）
//     · 运动块的包围框（像素坐标）  O_x_min/O_x_max/O_y_min/O_y_max
//     · 运动块数（**不是目标个数**）O_blk_cnt
//     · 本帧是否被判为全局光照突变  O_global_chg   （诊断用，要上 OSD）
//     · 形态学之前的原始运动块数    O_motion_raw   （诊断用）
//
//  ===========================================================================
//  ★★★ 2026-09-26 上板事故与本次修正（**本文件最重要的一节，先读这里**）
//  ===========================================================================
//  现象：**静止场景也出框**（已打位流 lab4_p7_release_20260926_2318）。
//        实测复现（新增场景 F：上半屏亮 200 / 下半屏暗 40、水平分界、完全静止）：
//            修前 → 每帧 valid=1、raw=7200、框 (8,8)-(1279,359)（整个上半屏）
//            修后 → 每帧 valid=0、raw=0
//
//  根因：上一版把背景**按列共享 160 个槽**（设计文档 §4.3 的"存储量 14400→160"）。
//        §4.3 的论证是"(by,bxc) 只需要上一帧同一个 (by,bxc) 的值"——
//        这句话**对「读」成立，对「写」不成立**：一个槽在一帧内会被 90 个块行
//        各写一次（by=0..89 写的是同一个 S_bg[bxc]）⇒ (by,bxc) 读到的**不是**
//        上一帧 (by,bxc) 的值，而是**本帧 (by−1,bxc) 刚写进去的值**。
//        于是背景被"同一列紧邻上方那一行的内容"整体拖走，在**水平分界处**
//        形成恒定的 |cur−bg| = 亮度阶差 ⇒ 静止画面里长期报运动。
//
//  ▶ 为什么 L1 里没抓到（这一条比 bug 本身更值得记）：
//       原来的 A~E 五个场景背景**垂直均匀**（纯色底 + 一个移动块），
//       而这恰好是"按列共享"唯一能工作的情形 ⇒ **bug 在 L1 里结构性看不见**。
//       与 P5 "TB 总从帧第 0 拍开始灌、于是相位 bug 仿真永远不出现"是同一类错误：
//       **测试激励没覆盖真实条件**。⇒ 本次新增静止的结构化场景 F/G/H。
//
//  ▶ 修法：背景改成 **每个块 (by,bxc) 一个值**（14400 个 × 8 bit，线性索引
//        by*160+bxc），存进 **ERAM**（`(* ram_style = "block" *)` +
//        寄存器化读地址）。顺带把 160×16 的累加器也搬进 ERAM
//        ⇒ 省掉原来两片分布式 LUTRAM（≈300 LUT），正好缓解 slice 压力。
//        之前那条"背景更新按块行抽样"的临时补丁**已删除**：
//        每块独立背景之后，一帧内每个块只被写一次，抽样就没有必要了
//        ⇒ 判决与背景更新**完全回到设计文档 §6.1 的公式**（无偏离）。
//
//  ▶ 资源（**未综合验证，报给 TD 复核**）：
//        背景 16384×8 = 131072 bit ≈ 8 块 ERAM（只用前 14400 个地址）
//        累加器  256×16 =   4096 bit ≈ 1 块 ERAM
//        合计 ≈ 9 块 ERAM（原设计实测 47/108 已用，余量够）
//        LUT：省掉 ~300 LUT 的分布式 LUTRAM，新增 ~22 FF 的地址寄存器。
//
//  ===========================================================================
//  ★★ 亮度代理为什么用 G 通道，不做 77/150/29 加权
//  ===========================================================================
//   `luma_stats` 算的 `Y = (77R+150G+29B)>>8` 要 12 个移位加法（≈180 LUT）。
//   运动检测是**差分**运算 —— 只要"亮度代理"与真实亮度**单调一致**，差分结果
//   就一致。G 占 Y 的 58.6%（150/256），是最强的单通道代理，而用 G 的代价是
//   **0**（直接切片，不需要任何算术）。
//   ⇒ 这是**刻意的近似**（不是"算错了亮度"）。切片位置与 `target_detect_96.v`
//     **完全一致**（同一个 tap、同一套字节序）。
//
//  ===========================================================================
//  ★★ 几何：8×8 块、每块 2 拍
//  ===========================================================================
//     每拍 4 像素（96 bit = 4×RGB888） ⇒ 每行 1280/4 = 320 拍
//     块宽 8 像素 = 8/4 = **2 拍**；块列 1280/8 = 160；块行 720/8 = 90
//     总块数 160×90 = 14400
//     一个块 = 8 行 × 2 拍 × 4 像素 = 64 像素
//     每拍 G 之和 ≤ 4×255 = 1020（10 bit）
//     一个块的总和 ≤ 8×2×1020 = **16320**（14 bit，留 16 bit 有余）
//     块亮度 = sum >> 6（÷64） ⇒ 0..255
//   ⇒ 块 `bxc` 在行内第 `2·bxc+1` 拍（**奇数拍**）定稿，且只有"块行的第 8 行"
//     （line%8==7）才定稿 ⇒ 每 2 拍正好定稿一个块。
//
//  ---------------------------------------------------------------------------
//  ★★ 一个必须自己核对过的巧合：帧末恰好落在"最后一个块定稿"那一拍
//  ---------------------------------------------------------------------------
//     719 = 8×89 + 7  ⇒ 最后一行是块行 89 的第 8 行（line%8==7 ✓）
//     319 是奇数      ⇒ 该行最后一拍正好定稿块 bxc = 159 ✓
//   ⇒ 帧末 = (P_col==319) && (P_line==719) 与
//           "最后一个块 (by=89,bxc=159) 定稿" 是**同一拍**，
//     所以**不需要任何收尾状态机**，也不需要多等一拍。
//   ★ 这条性质**依赖 1280×720 + 每拍 4 像素**这套几何；改参数时必须重新核对。
//     ⚠ 也正因如此，帧结算必须放在**定稿那一拍组合算出**（见"两拍时序"），
//       不能把判决再往后打一拍 —— 否则最后一拍的运动块会漏掉（面积占满时
//       会少 1 块、框的右边界会短 8 像素）。这是本模块最容易写错的一处。
//
//  ===========================================================================
//  ★★★ ERAM 的两拍读-改-写时序（本次改动**重新推导过**的地方）
//  ===========================================================================
//   ERAM 与分布式 LUTRAM 的关键差别：**ERAM 要求读地址寄存器化**
//   （`logo_rom_eram.v` 里那条 PH1P 硬约束：地址与数据输入必须与时钟同步，
//     否则工具不做时序分析、内容可能不可预测地翻转）。
//
//   ⚠ 直觉上的担心："地址打一拍 ⇒ 读数据整体挪后一拍 ⇒ 原来的两拍节奏就废了。"
//     这个担心**只在"地址由本拍的位置组合给出、再打一拍"时成立**。本设计把它
//     绕开：**地址寄存器提前一个块更新好**，于是它在本块的偶数拍上就已经是
//     本块的地址了。推导（N = 当前块的线性索引）：
//
//      拍 2k   （块 N 的**偶数拍**）：S_bg_ra/S_acc_ra 已经 = N
//                                     （在上一个块的奇数拍尾就更新好了）
//      拍 2k+1 （块 N 的**奇数拍**）：读回值 = RAM[N]   ← 正好有效，与 LUTRAM 版完全一致
//                                     判决 + 用同一个地址 N 写回新值
//                                     本拍**尾**把地址寄存器更新成 N+1（给下一个块用）
//      ⇒ **仍然是每块 2 拍**，既不需要 4 拍周期、也不需要真双口/块加宽。
//
//   ★ 两个地址寄存器分别是什么：
//       S_bg_ra  [13:0] 线性块索引 N = by*160 + bxc，只在**定稿拍**更新
//                       （一个帧内恰好走 0..14399 一遍 ⇒ 每块恰好读一次、写一次）
//       S_acc_ra [7:0]  块列 bxc，每 2 拍更新一次（累加器每行都要读改写）
//   ★ 写口与读口共用同一个地址寄存器（读在偶数拍有效、写在奇数拍发生，错开一拍）
//     ⇒ 简单双口（一读一写）就够；即使综合器为了满足 ERAM 的端口时序把
//       we/addr/din 再打一拍，也只是把写回推迟一拍 —— 而同一地址的下一次读
//       发生在**320 拍后（累加器）或下一帧（背景）**，绝不会撞上 ⇒ 功能不受影响。
//   ★ 帧相位对齐那一拍：读地址寄存器可能停在任意值（读到垃圾没关系 ——
//     重对齐一定伴随"学习帧"，那一整帧的 mot 强制为 0、背景是直接装载，
//     读回值根本不被使用），同时在这一拍把两个地址寄存器都清 0，
//     于是**从下一个块起地址就完全正确**（含写地址 —— 上一版用组合读地址时，
//     写地址跟着位置走，重对齐那一拍会把 block 0 的部分和写到错误地址去）。
//   ★ 定稿行（line%8==7）累加器**写回 0**（不是写回总合）：同一拍只允许一次写，
//     于是"清累加器给下一个块行"和"写回本行部分和"用**同一个写口**完成。
//
//  ===========================================================================
//  ★★ 判决与背景更新（sigma-delta，饱和）
//  ===========================================================================
//     diff = |cur − bg|
//     mot  = (diff > MOT_TH)                       // 严格大于
//     bg  <= (cur>bg) ? bg+BG_STEP : ((cur<bg) ? bg−BG_STEP : bg)
//   **必须饱和**：bg 是 8 bit，若不加饱和，`bg+BG_STEP` 会在 255 处回绕成 0、
//   `bg−BG_STEP` 会在 0 处下溢成 255 ⇒ 背景一头撞到极值就**跳到另一头**，
//   之后每一帧都满屏误报（而且这种错只在特定光照下出现，极难查）。
//   ⇒ 上溢钳到 255、下溢钳到 0，用 9 位加减的进位/借位位判（零除法零乘法）。
//
//   为什么不用纯帧差：帧差比的是"相邻两帧"，AE 一改亮度整帧差值都变大 ⇒
//   满屏误报。sigma-delta 让 bg **缓慢跟踪**场景，光照渐变被吸收掉，只有
//   "比背景更新快得多"的变化才判成运动。
//   ★ 背景**每帧每块更新一次**（这是正确的速率）。整帧亮度阶跃时 bg 要
//     |Δ|/BG_STEP 帧才追上（+40 阶跃、STEP=1 ⇒ 40 帧 ≈ 0.67 s@60fps）；
//     这段时间里每帧都会被"全局突变抑制"判掉（见下）⇒ 不会误报成运动目标。
//
//  ===========================================================================
//  ★★ 全局光照突变抑制（P6 之后必需，不是可选）
//  ===========================================================================
//   AE 一个台阶（曝光跳一档）会让整帧瞬间偏离背景，即使 sigma-delta 也会
//   满屏误报。加一条全局变化检测：
//     本帧运动块数 > 全部块数的 GLOBAL_PCT%（默认 50%）⇒ 判为全局突变：
//        O_global_chg = 1，O_valid = 0（本帧不报运动）
//   ★ 用**形态学之前的原始块数**（O_motion_raw）做这个判据，理由：
//     原始块数才是"整帧变了多少"的诚实度量；腐蚀后的计数被图像边界削掉
//     一圈（下面会讲），拿它判阈值等于把"边界效应"混进光照判据里。
//   ★ 阈值是**编译期常量**：`GLOBAL_LIMIT = 14400 × PCT / 100`，且因为
//     14400/100 = 144 = 128+16，可以直接写成移位加法 `(PCT<<7)+(PCT<<4)`，
//     连常量乘法都不写（本模块 DSP 必须为 0）。
//   ★ O_blk_cnt 在全局突变时**不为 0**（它诚实报告腐蚀后的块数），
//     "本帧不算运动"这件事只由 O_valid 表达 —— 下游必须看 O_valid 再决定画框。
//
//  ===========================================================================
//  ★★ 去噪：2×2 腐蚀（不是 3×3 形态学）
//  ===========================================================================
//   3×3 形态学要 480 bit 的 3 行窗口 + 每块 9 输入 min/max ≈ 600 LUT，且
//   "右邻居"当拍不可得还要再延迟一个块；2×2 只要 ~170 LUT。
//     motion_eroded = 本块 ∧ 左块 ∧ 上块 ∧ 左上块        （四者都是**原始**运动位）
//   ★ "上一块行位图"的省 LUT 实现（先看访问顺序，再决定存什么）：
//     相邻块行之间正好隔 **160 个块** ⇒ 用一条 **160 级移位延迟线** 就够了：
//        S_up_dly <= {S_up_dly[158:0], w_mot};   // 每个定稿块移一位
//     处理块 N（帧内第 N 个块）时，`S_up_dly[j] = mot(N−1−j)`（上一次移位的结果），
//     于是 `S_up_dly[159] = mot(N−160)` = **上一块行同一 bxc**（上邻居），
//     是**固定位选**，不需要 160:1 读 mux，也不需要 160 bit 的写译码。
//     （纯移位无并行装载 ⇒ 160 FF + 0 LUT，只有"清零"那一下要一点逻辑。）
//   ★★ "左上块"不能取 `S_up_dly[158]` —— 那是 `mot(N−159)` = 上一块行的
//      **右边**一个（bxc+1），不是左边！上一版就是这么写的，仿真+独立模型立刻
//      抓到：亮块的**最右一列**永远腐蚀不掉（实测 342 块而不是 361 块、
//      框右边界 471 而不是 479）。正确做法与"左块"同构：用 **1 bit 寄存器**
//      记住"上一个定稿块的上邻居"，它正好是本次的上左邻居：
//        S_up_prev <= w_mot_up;      // 上一块行的 (bxc) ⇒ 本块的 (bxc−1)
//   ★ "左块"用 1 bit 延迟（上一个定稿块的 mot），bxc==0 时**强制为 0**；
//     "左上块"同一条规则（bxc==0 ⇒ 图像外 ⇒ 非运动）。
//   ★ 边界处理（**诚实标注**）：图像外当作**非运动**（标准腐蚀的零填充）。
//     于是
//       · 块行 0 **永远不可能**腐蚀后为 1（上邻居=0）
//       · 块列 0 **永远不可能**腐蚀后为 1（左邻居=0）
//     ⇒ 框的**上边界与左边界各内缩一个块（8 像素）**；若运动物体正好贴着
//       画面顶端/左端，最上面/最左面那一块宽的运动会**判不出来**。
//     这不是 bug 而是"只腐蚀不膨胀"的必然代价，写在报告里。
//     为了让"块行 0 上邻居=0"在**每一帧**都成立（而不是继承上一帧最后一个
//     块行的残留），延迟线在**帧末那一拍清零**（见 S_up_dly 的更新分支）。
//   ★ 追加的"最小块数"门限 MIN_BLK 同时保留（治孤立斑点，很便宜）。
//   ★★ 只腐蚀、**不膨胀**，也不做连通域标记：
//       · 框比"理想形态学方案"略小（最多 1 个块 = 8 像素）；
//       · `O_blk_cnt` 是**运动块数**，**不是目标个数** —— 与 P5 的 O_tile_cnt
//         一样，OSD 上必须按真实含义标注，不能写成 "N=" 冒充目标计数。
//
//  ===========================================================================
//  ★★ 首帧 = 背景学习帧（为什么必须有）
//  ===========================================================================
//   复位/重新对齐之后，S_bg 里没有任何有效值（硬件上电是任意值，仿真里是 X）。
//   若直接拿它比对，第一帧会把整幅画面判成运动（diff=|cur−0|）。
//   ⇒ 复位后（以及**相位重对齐**后）的第一整帧进入"学习"模式：
//         mot = 0（不报运动）、bg <= cur（直接装载）
//      一整帧恰好把 160×90 个背景值全部写一遍（线性索引 0..14399 各一次）
//      ⇒ 第 2 帧起就是正常检测。
//   这既去掉了 X/上电垃圾，也顺便解决"开机第一帧满屏框"这个必然现象。
//   ⚠ 学习模式**只对一帧**生效（帧末清除），不会长期掩盖运动。
//
//  ===========================================================================
//  ★★ 帧相位对齐（照抄 target_detect_96.v 的同一套）
//  ===========================================================================
//   本模块的帧/行边界是**纯拍数自计时**（铁律四：awb 的 tuser 组合直通而 tvalid
//   流水延迟，用 `tvalid&&tuser` 做帧结算**永不成立**，P5 上板事故）。拍数从
//   复位释放开始数 ⇒ 复位时摄像头在哪一行，就成了"第 0 行"，坐标带任意常数偏移。
//   修法：用 `I_tuser`（帧首脉冲，单比特、每帧一次）把计数器掰回真实帧首。
//
//   ★★ 漂移陷阱（必须写清楚）：**对齐那一拍必须照常参与累加，不能丢弃**。
//      做法是把 P_*（P_col/P_line/P_bxc/P_by）在**对齐那一拍强制为 0**，
//      让这一拍作为新帧的第 0 拍被**正常处理**（它的 4 个 G 照样寄存在
//      S_g_even、照样在该块的奇数拍被累加）。
//      若图省事"丢弃对齐那一拍"，每帧就少算一拍 ⇒ 帧边界每帧漂 1 拍 = 4 像素，
//      1 秒漂 240 像素，画面会越来越歪（P5 上板就是这么栽的）。
//
//   ★ 只在**相位真的不对**时才做重同步（`w_resync`）：自计时正常时 tuser 正好
//     落在 S_col==0 && S_line==0 那一拍，此时**不**置学习标志（否则每帧都变成
//     学习帧，运动就永远报不出来）。相位不对时才置学习标志 + 清延迟线/计数器/
//     两个 RAM 地址寄存器，把"对齐前那半截帧的脏状态"整体丢掉。
//
//  ===========================================================================
//  ★ 零 DSP（铁律三）
//  ===========================================================================
//   全模块只有比较 / 加减 / 移位 / 位选，**没有任何 `*`**（连常量乘法也用
//   移位加法代替），判决不做除法（MOT_TH 是绝对阈值，块亮度已经是均值）。
//
//  ★ 跨域：接口里只有 O_frame_start（没有 O_tog）⇒ 按接口来：帧末那一拍把
//    整组结果锁存并给出单拍脉冲，由下游（2-FF 同步 + 边沿捕获）自己处理。
// ============================================================================
`timescale 1ns/1ps

module motion_detect #(
    parameter integer IMG_WIDTH   = 1280,
    parameter integer IMG_HEIGHT  = 720,
    parameter integer PX_PER_BEAT = 4,       // ⚠ 96 bit 接口固定 4 像素/拍，只支持 4
    parameter [7:0]   MOT_TH      = 8'd24,   // |cur-bg| 判决阈值（8 bit 亮度域）
    // ★★ MOT_TH 由 18 提到 **24**（2026-09-26，依据 tools/check_motion_detect.py
    //    --study 的实测，静止画面 + 每像素噪声 ±N，14400 块 × 11 帧 = 158400 次机会）：
    //       N=8  ⇒ 块级 max|cur-bg| = 5     （TH=18 与 TH=24 都 0 次误报）
    //       N=16 ⇒ 8                        （都 0）
    //       N=24 ⇒ 9                        （都 0）
    //       N=32 ⇒ 14                       （都 0，但 TH=18 只剩 1.29 倍余量）
    //       N=48 ⇒ 33                       （TH=18 误报 478 次 / TH=24 误报 47 次 / TH=32 才 2 次）
    //    噪声被 8×8 = 64 像素平均压掉 8 倍 ⇒ 块级 σ ≈ N/(8√3)，所以块级噪声很小；
    //    取 24 是"给 N≈32 的极端高增益噪声留 1.7 倍余量"与"别丢掉低对比度真运动"
    //    之间的折中。真实运动的块亮度差在本工程测试图案里是 **160**（6.7 倍余量）
    //    ⇒ 提阈值对"挥手出框"这类高对比运动**没有影响**；现场仍可按 OSD 计数微调。
    parameter integer BG_STEP     = 1,       // sigma-delta 背景更新步长
    parameter integer GLOBAL_PCT  = 50,      // 运动块占比超过它就判为全局光照突变
    parameter integer MIN_BLK     = 4,       // 合格运动块数（腐蚀后）下限
    parameter integer ALIGN_ON_TUSER = 1     // 1=用 I_tuser 做帧相位对齐；0=纯自计时（对照用）
)(
    input  wire        I_clk,        // ISP 域
    input  wire        I_rst_n,
    input  wire        I_tuser,      // 帧首脉冲（仅用于相位对齐，见 target_detect_96.v 同一套说明）
    input  wire [95:0] I_tdata,      // p0{R,G,B} p1{...} p2{...} p3{...}，每拍 4 像素
    input  wire        I_tvalid,
    output reg  [10:0] O_x_min, O_x_max,   // 像素坐标（含端点）
    output reg  [9:0]  O_y_min, O_y_max,
    output reg  [13:0] O_blk_cnt,    // 运动块数（**不是目标个数**）
    output reg         O_valid,      // 本帧是否有运动（已含全局突变抑制）
    output reg         O_global_chg, // 本帧被判为全局光照突变（诊断用）
    output reg         O_frame_start,// 帧结算单拍（跨域握手）
    output reg  [13:0] O_motion_raw  // 形态学前的运动块数（诊断用）
);

    // ================================================================ 常量
    localparam integer BEAT_PER_LINE = IMG_WIDTH  / PX_PER_BEAT;   // 320 拍/行
    localparam integer BLK_COLS      = IMG_WIDTH  / 8;             // 160
    localparam integer BLK_ROWS      = IMG_HEIGHT / 8;             // 90
    localparam integer BLK_TOTAL     = BLK_COLS * BLK_ROWS;        // 14400
    // ★ 上面这个 `*` 是**编译期常量表达式**（elaboration 时求值 ⇒ 综合后就是一个常数，
    //   不可能映射到 DSP）。真正的**硬件数据通路**上一个 `*` 都没有：全部是比较/加减/
    //   移位/位选。GLOBAL_LIMIT 连常量乘法也刻意避开了（见下）。
    //   （`(* ram_style = ... *)` 是综合属性，不是乘法。）
    localparam integer BEAT_PER_BLK  = 8 / PX_PER_BEAT;            // 2 拍/块（P_bxc=P_col[8:1] 的依据）
    // ★★ RAM 深度都取 2 的幂，好让 ERAM 映射可预测（一条 2048 深的块刚好占满）：
    //    背景需要 BLK_TOTAL = 14400 个 ⇒ 取 16384（只用前 14400 个，浪费 ≈12%）；
    //    累加器只需要 160 个（一个块行）⇒ 取 256。
    localparam integer BG_DEPTH      = 16384;                      // 2^14 ≈ 8 块 ERAM
    localparam integer ACC_DEPTH     = 256;                        // 256×16 ≈ 1 块 ERAM
    localparam [13:0]  BG_LAST       = BLK_TOTAL - 1;              // 14399（线性索引的最后一格）

    // ---- 全局突变门限：BLK_TOTAL × GLOBAL_PCT / 100 ----
    //   BLK_TOTAL/100 = 144 = 128+16 ⇒ 用移位加法，**不写 `*`**（DSP 必须为 0）。
    //   ⚠ 这条等式依赖 BLK_TOTAL=14400；改分辨率时必须回头核对（并在
    //     tools/check_motion_detect.py 里穷举比对 PCT 0..100）。
    //   ⚠ 这里刻意**不做 GLOBAL_PCT 的位选**：Verilog-2001 里对 integer 型
    //     parameter 做位选不合法，必须靠中间 localparam 收窄位宽。
    localparam [7:0]  GLOBAL_PCT8  = GLOBAL_PCT;
    localparam [13:0] GLOBAL_LIMIT = ({6'd0, GLOBAL_PCT8} << 7)
                                   + ({6'd0, GLOBAL_PCT8} << 4);
    localparam [13:0] MIN_BLK14    = MIN_BLK;
    localparam [8:0]  BG_STEP9     = BG_STEP;      // 加宽 1 位做饱和判断

    // ================================================================ 输入像素（G 通道代理）
    //   切片位置与 target_detect_96.v 完全一致（同一个 tap、同一套字节序）
    wire [7:0] w_p0_g = I_tdata[87:80];
    wire [7:0] w_p1_g = I_tdata[63:56];
    wire [7:0] w_p2_g = I_tdata[39:32];
    wire [7:0] w_p3_g = I_tdata[7:0];

    // 本拍 4 个 G 之和：≤ 4×255 = 1020（10 bit）
    wire [9:0] w_gsum = {2'b00, w_p0_g} + {2'b00, w_p1_g}
                      + {2'b00, w_p2_g} + {2'b00, w_p3_g};

    // ================================================================ 位置计数器（自计时）
    reg  [8:0] S_col;    // 0..319（BEAT_PER_LINE-1）
    reg  [9:0] S_line;   // 0..719（IMG_HEIGHT-1）

    // ★ 帧相位对齐（照抄 target_detect_96.v）
    wire w_align = I_tvalid && I_tuser && (ALIGN_ON_TUSER != 0);

    wire [8:0] P_col  = w_align ? 9'd0 : S_col;
    wire [9:0] P_line = w_align ? 10'd0 : S_line;

    wire [7:0] P_bxc  = P_col[8:1];              // 块列 0..159
    wire [6:0] P_by   = P_line[9:3];             // 块行 0..89
    wire       P_odd  = P_col[0];                // 1 = 本块的**第 2 拍**（定稿拍）
    wire       P_fin  = (P_line[2:0] == 3'd7);   // line%8==7：块行的第 8 行（定稿行）

    // ★ 帧末：最后一个块定稿那一拍（见文件头"巧合"一节）
    wire w_frame_last = (P_col == BEAT_PER_LINE - 1) && (P_line == IMG_HEIGHT - 1);

    // ★ 相位**真的不对**才算重同步（自计时正确时 tuser 正好落在 (0,0) 那一拍）
    //   ⚠ 若不加这个条件、每帧都当重同步，学习模式会每帧触发 ⇒ 永远报不出运动。
    wire w_resync = w_align && ((S_col != 9'd0) || (S_line != 10'd0));

    // ================================================================ 两个 RAM（ERAM，块 RAM）
    //   ★ 背景：**每个块一个值**，线性索引 N = by*160 + bxc（0..14399），一帧写一遍。
    //     这是本次上板事故的修正点：按列共享（160 槽）会让背景被同帧上方行拖走。
    //   ★ 累加器：块行内 8 行的部分和，按 bxc 索引，定稿行写 0 清空给下一个块行。
    //   ★ `ram_style="block"` 是本工程已验证能推断 ERAM 的写法（见 logo_rom_eram.v /
    //     cartoon_96.v）；**读地址必须寄存器化**，见文件头"ERAM 两拍时序"一节。
    (* ram_style = "block" *) reg [7:0]  S_bg  [0:BG_DEPTH-1];
    (* ram_style = "block" *) reg [15:0] S_acc [0:ACC_DEPTH-1];

    reg [13:0] S_bg_ra;     // 背景读/写地址 = 当前块的线性索引（提前一个块更新好）
    reg [7:0]  S_acc_ra;    // 累加器读/写地址 = 当前块列 bxc（提前一个块更新好）

    reg [15:0] S_acc_rd;    // 累加器读回（奇数拍有效）
    reg [7:0]  S_bg_rd;     // 背景读回（奇数拍有效）
    reg [9:0]  S_g_even;    // 本块"偶数拍"那 4 个 G 之和（奇数拍要用）

    reg S_acc_seed;         // 累加器播种（对齐后第一行忽略读回值，见文件头）
    reg S_bg_init;          // 背景学习帧

    // ================================================================ 块亮度与判决（组合）
    //   16 位总合 = (播种?0:累加器读回) + 本块偶数拍之和 + 本拍之和
    //   （≤ 8×2×1020 = 16320，14 bit 足够，16 bit 有余量）
    wire [15:0] w_blk_sum = (S_acc_seed ? 16'd0 : S_acc_rd)
                          + {6'd0, S_g_even} + {6'd0, w_gsum};
    //   ÷64：总合 ≤ 16320 = 0x3FC0 ⇒ bit14 恒 0，取 [13:6] 就是精确的 sum>>6，
    //   而且天然落在 0..255（不需要额外的截断/比较）
    wire [7:0]  w_blk = w_blk_sum[13:6];

    //   |cur − bg|：无符号相减，先比大小决定谁减谁（避免有符号运算）
    wire [7:0]  w_diff = (w_blk >= S_bg_rd) ? (w_blk - S_bg_rd)
                                            : (S_bg_rd - w_blk);

    wire w_mot = S_bg_init ? 1'b0 : (w_diff > MOT_TH);

    //   sigma-delta 更新，**饱和**（9 位加减，用进/借位判溢出，无除法无乘法）
    wire [8:0] w_bg_up = {1'b0, S_bg_rd} + BG_STEP9;
    wire [8:0] w_bg_dn = {1'b0, S_bg_rd} - BG_STEP9;
    wire [7:0] w_bg_step = (w_blk > S_bg_rd) ? (w_bg_up[8] ? 8'd255 : w_bg_up[7:0])
                         : (w_blk < S_bg_rd) ? (w_bg_dn[8] ? 8'd0   : w_bg_dn[7:0])
                         : S_bg_rd;
    wire [7:0] w_bg_new = S_bg_init ? w_blk : w_bg_step;   // 学习帧直接装载

    // ---- RAM 端口（读口地址 = 地址寄存器，写口地址 = 同一个寄存器）----
    //   ★ 写使能/写数据是组合给出的：即使综合器为满足 ERAM 端口时序把它们再打一拍，
    //     也只是把写回推迟一拍 —— 同一地址的下一次读在 320 拍后（累加器）或
    //     下一帧（背景），绝不会撞上 ⇒ **功能不受影响**（见文件头时序推导）。
    wire        w_acc_we = I_tvalid && P_odd;                 // 每个块的奇数拍写回部分和
    wire [7:0]  w_acc_wa = S_acc_ra;
    wire [15:0] w_acc_wd = P_fin ? 16'd0 : w_blk_sum;         // 定稿行写 0 = 清累加器（一次写干两件事）
    wire        w_bg_we  = I_tvalid && P_odd && P_fin;        // 只在定稿拍（一帧每块一次）
    wire [13:0] w_bg_wa  = S_bg_ra;
    wire [7:0]  w_bg_wd  = w_bg_new;

    // ---------------- RAM 本体：同步写 + 寄存器化读地址 + 寄存输出（推断 ERAM）----
    always @(posedge I_clk) begin
        if (w_bg_we)  S_bg [w_bg_wa ] <= w_bg_wd;
        if (w_acc_we) S_acc[w_acc_wa] <= w_acc_wd;
        S_bg_rd  <= S_bg [S_bg_ra];       // 偶数拍地址已是本块 ⇒ 奇数拍读回值有效
        S_acc_rd <= S_acc[S_acc_ra];
    end

    // ================================================================ 2×2 腐蚀
    reg [159:0] S_up_dly;    // 160 级延迟线：[159] 退出的是"160 个块之前"= 上一块行同 bxc
    reg         S_mot_left;  // 上一个定稿块的原始运动位（"左块"）
    reg         S_up_prev;   // 上一个定稿块的**上邻居**位（⇒ 本块的"左上块"）

    wire w_mot_up     = S_up_dly[BLK_COLS-1];
    //  ⚠ 不能用 S_up_dly[158]（那是上一块行的右邻），见文件头"左上块"那一段
    wire w_mot_upleft = (P_bxc == 8'd0) ? 1'b0 : S_up_prev;
    wire w_mot_left   = (P_bxc == 8'd0) ? 1'b0 : S_mot_left;   // bxc==0 ⇒ 图像外，当作非运动
    wire w_eroded     = w_mot && w_mot_left && w_mot_up && w_mot_upleft;

    // ================================================================ 计数 / 包围框（块坐标）
    reg [13:0] S_raw_cnt;    // 形态学前的运动块数
    reg [13:0] S_ero_cnt;    // 腐蚀后的运动块数（= O_blk_cnt）
    reg        S_any;        // 本帧是否已有合格块
    reg [7:0]  S_bx_min, S_bx_max;
    reg [6:0]  S_by_min, S_by_max;

    // ★★ 必须用**组合的 next 值**：帧末那一拍要结算，而帧末那一拍本身就是
    //    最后一个块的定稿拍 —— 若在这里读寄存器（非阻塞赋值的老值），
    //    最后一个块就漏掉了（面积占满时会少 1 块、框右边界短 8 像素）。
    wire [13:0] w_raw_next = S_raw_cnt + {13'd0, w_mot};
    wire [13:0] w_ero_next = S_ero_cnt + {13'd0, w_eroded};

    wire w_upd = w_eroded;
    wire [7:0] w_bxmin_n = (w_upd && (!S_any || (P_bxc < S_bx_min))) ? P_bxc : S_bx_min;
    wire [7:0] w_bxmax_n = (w_upd && (!S_any || (P_bxc > S_bx_max))) ? P_bxc : S_bx_max;
    wire [6:0] w_bymin_n = (w_upd && (!S_any || (P_by  < S_by_min))) ? P_by  : S_by_min;
    wire [6:0] w_bymax_n = (w_upd && (!S_any || (P_by  > S_by_max))) ? P_by  : S_by_max;
    wire       w_any_n   = S_any | w_upd;

    // 全局突变判决（用**原始**块数，理由见文件头）
    wire w_global_now = (w_raw_next > GLOBAL_LIMIT);

    // 块坐标 → 像素坐标：×8 = 左移 3 位（零成本）
    wire [10:0] w_px_min = {w_bxmin_n, 3'b000};
    wire [10:0] w_px_max = {w_bxmax_n, 3'b000} + 11'd7;
    wire [9:0]  w_py_min = {w_bymin_n, 3'b000};
    wire [9:0]  w_py_max = {w_bymax_n, 3'b000} + 10'd7;

    // ================================================================ 主时序
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            S_col <= 9'd0;
            S_line <= 10'd0;
            S_g_even <= 10'd0;
            S_acc_seed <= 1'b1;      // 复位后第一行重新播种累加器
            S_bg_init  <= 1'b1;      // 复位后第一帧 = 背景学习帧
            S_bg_ra  <= 14'd0;       // 线性块索引从 0 开始（学习帧会把 0..14399 全写一遍）
            S_acc_ra <= 8'd0;        // 块列从 0 开始
            // ⚠ S_acc_rd / S_bg_rd **不在这里赋值**：它们由 RAM 那个 always 块独占驱动
            //   （同一个 reg 被两个 always 块赋值 ⇒ 综合报"多驱动"）。上电时读回值是
            //   垃圾/X 也没关系：累加器读回在播种行被忽略、背景读回只在非学习帧用，
            //   而那时背景已经被学习帧整帧写过一遍了。
            S_up_dly <= 160'd0;
            S_mot_left <= 1'b0;
            S_up_prev  <= 1'b0;
            S_raw_cnt <= 14'd0;
            S_ero_cnt <= 14'd0;
            S_any     <= 1'b0;
            S_bx_min <= 8'd0;  S_bx_max <= 8'd0;
            S_by_min <= 7'd0;  S_by_max <= 7'd0;
            O_x_min <= 11'd0;  O_x_max <= 11'd0;
            O_y_min <= 10'd0;  O_y_max <= 10'd0;
            O_blk_cnt <= 14'd0;
            O_valid <= 1'b0;
            O_global_chg <= 1'b0;
            O_frame_start <= 1'b0;
            O_motion_raw <= 14'd0;
        end else begin
            O_frame_start <= 1'b0;   // 默认单拍

            if (I_tvalid) begin
                // ---------------- ① 偶数拍：寄存本拍 G 之和（奇数拍要用）----------------
                //   ★ 对齐那一拍也走这里（P_odd 被强制为 0）⇒ 这一拍**不丢**，
                //     否则每帧漂 1 拍 = 4 像素（见文件头"漂移陷阱"）。
                if (!P_odd) S_g_even <= w_gsum;

                // ---------------- ② 奇数拍：把累加器地址寄存器推到"下一个块" ----------------
                //   ★ 这就是"ERAM 要求地址寄存器化"的应对：地址**提前一个块**就位，
                //     于是本块的偶数拍上地址已经是本块的 ⇒ 奇数拍读回值有效，
                //     仍然是每块 2 拍（推导见文件头）。
                if (P_odd) begin
                    S_acc_ra <= (P_bxc == BLK_COLS - 1) ? 8'd0 : (P_bxc + 8'd1);
                end

                // ---------------- ③ 奇数拍定稿：判决 + 腐蚀 + 计数 + 包围框 ----------------
                if (P_odd && P_fin) begin
                    S_bg_ra <= (S_bg_ra == BG_LAST) ? 14'd0 : (S_bg_ra + 14'd1);

                    S_raw_cnt <= w_raw_next;
                    S_ero_cnt <= w_ero_next;
                    S_any     <= w_any_n;
                    S_bx_min  <= w_bxmin_n;
                    S_bx_max  <= w_bxmax_n;
                    S_by_min  <= w_bymin_n;
                    S_by_max  <= w_bymax_n;

                    // "左块"延迟：本拍结束后 S_mot_left 就是**本块**的运动位，
                    // 下一个块用它当左邻居（bxc==0 时被强制 0，避免继承上一块行
                    // 最后一个块的残留）
                    S_mot_left <= w_mot;
                    // "左上块"延迟：本拍结束后 S_up_prev = 本块的**上邻居**位，
                    // 下一个块用它当"左上块"（同样在 bxc==0 被强制 0）。见文件头。
                    S_up_prev  <= w_mot_up;

                    // 160 级延迟线：每个定稿块移一位 ⇒ 退出来的 [159] 正好是
                    // "160 个块之前"那一块 = 上一块行同一 bxc
                    // ★ 帧末那一拍**清零**：让"块行 0 的上邻居 = 图像外 = 非运动"
                    //   在每一帧都严格成立（否则会继承上一帧最后一块行的残留，
                    //   使块行 0 的腐蚀结果依赖上一帧，独立模型就无法用
                    //   "图像外=0"这一条简单规则描述它）。
                    // ★ w_resync 也清零：把对齐前那半截帧的脏历史整体丢掉
                    //   （与帧末清零共用同一个写口，不额外花逻辑）。
                    if (w_resync || w_frame_last) S_up_dly <= 160'd0;
                    else                          S_up_dly <= {S_up_dly[158:0], w_mot};
                end

                // ---------------- ④ 累加器播种标志：对齐那拍置位，行 0 走完清除 ----------------
                if (w_align) S_acc_seed <= 1'b1;
                else if ((P_col == BEAT_PER_LINE - 1) && (P_line == 10'd0))
                    S_acc_seed <= 1'b0;

                // ---------------- ⑤ 学习标志：复位/重同步置位，帧末清除 ----------------
                if (w_resync)     S_bg_init <= 1'b1;
                if (w_frame_last) S_bg_init <= 1'b0;

                // ---------------- ⑥ ★ 帧相位对齐那一拍：把 RAM 地址寄存器掰回 0 ----------------
                //   对齐拍是**偶数拍**（P_odd 被强制 0），与 ② 的更新不冲突。
                //   放在此处 ⇒ 优先级高于 ②/③（同一拍只有对齐命中这里）。
                //   ⚠ 读地址在这一拍可能还停在任意值（读到垃圾无害：重对齐必然伴随
                //     学习帧，那一整帧 mot 强制为 0、bg 直接装载）；但从这一拍之后
                //     地址就完全正确了 —— **包括写地址**（上一版用组合读地址时，
                //     写地址跟着位置走，重对齐那一拍会把 block 0 的部分和写错位置）。
                if (w_align) begin
                    S_bg_ra  <= 14'd0;
                    S_acc_ra <= 8'd0;
                end

                // ---------------- ⑦ ★ 帧末结算（必须放在计数更新之后）----------------
                //   ⚠ 顺序要紧：③ 里已经写了 S_raw_cnt/S_ero_cnt/包围框，这里用
                //     "组合 next 值"结算，并且**放在后面**，让帧末清零覆盖 ③ 的更新。
                if (w_frame_last) begin
                    // 无运动时把框显式清零（而不是留下残值）：虽然 O_valid=0 时
                    // 下游不该画框，接口语义明确更安全（与 target_detect_96 一致）
                    O_x_min <= w_any_n ? w_px_min : 11'd0;
                    O_x_max <= w_any_n ? w_px_max : 11'd0;
                    O_y_min <= w_any_n ? w_py_min : 10'd0;
                    O_y_max <= w_any_n ? w_py_max : 10'd0;
                    O_blk_cnt    <= w_ero_next;      // 腐蚀后块数（**不是目标个数**）
                    O_motion_raw <= w_raw_next;      // 形态学前的原始块数（诊断）
                    O_global_chg <= w_global_now;
                    O_valid      <= (w_ero_next >= MIN_BLK14) && !w_global_now;
                    O_frame_start <= 1'b1;

                    S_raw_cnt <= 14'd0;
                    S_ero_cnt <= 14'd0;
                    S_any     <= 1'b0;
                    S_bx_min <= 8'd0; S_bx_max <= 8'd0;
                    S_by_min <= 7'd0; S_by_max <= 7'd0;
                end

                // ---------------- ⑧ 位置推进（从 P_* 出发，对齐那拍照常推进）----------------
                if (P_col == BEAT_PER_LINE - 1) begin
                    S_col  <= 9'd0;
                    S_line <= (P_line == IMG_HEIGHT - 1) ? 10'd0 : (P_line + 10'd1);
                end else begin
                    S_col  <= P_col + 9'd1;
                    S_line <= P_line;
                end
            end
        end
    end

endmodule
