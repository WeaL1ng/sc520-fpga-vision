// ============================================================================
//  target_detect_96.v  ---  颜色目标检测 + 包围框（P5，扩展要求② + 高阶要求②）
//
//  官方原话：
//    扩展(2) "实现基于视频内容的目标检测与识别功能，对简单目标（如几何形状或
//             特定物体）进行识别，并在输出画面中叠加检测结果与文字说明"
//    进阶(2) "动态目标跟踪与坐标叠加"
//
//  ---------------------------------------------------------------------------
//  ★ 为什么不用完整连通域标记（CCL）
//  ---------------------------------------------------------------------------
//   two-pass union-find 要整帧行缓冲 + 等价表，720p 上太贵。本模块用
//   **tile 投影统计**：画面切成 16×9 = 144 个 80×80 的 tile，一个 tile 内命中
//   像素数 ≥ 阈值就认为该 tile "有目标"，再对所有合格 tile 求包围框。
//
//  ---------------------------------------------------------------------------
//  ★ 为什么把检测放在 ISP 域（而不是显示域）
//  ---------------------------------------------------------------------------
//   实测（P4c 布线后）：
//       MIPI_RX_BYTE_CLK(ISP) 70.631 MHz，需 59.995 ⇒ **+17.7%**
//       HDMI_PIXEL_CLK(显示)  83.340 MHz，需 75.002 ⇒ **+11.1%** ← 最紧，
//                                              且关键路径是"布线拥塞型"
//   本模块约 800 LUT + 1.3 kFF。若放显示域会直接压垮那个域。
//   ⇒ 检测在 ISP 域做，**只把每帧几个标量**乒乓送到显示域画框。
//     代价：框比画面**滞后约 2 帧**（≈33 ms，DDR 4-BANK 帧缓冲的结构延迟），
//           是**恒定滞后**而非抖动。
//
//  ---------------------------------------------------------------------------
//  ★ 零 DSP、零除法、零有符号运算（本项目铁律三）
//  ---------------------------------------------------------------------------
//   颜色空间用 CSD 移位加法，并用 **+32768 偏置**技巧彻底避开有符号运算：
//       Cb = (128B −  43R − 85G) >> 8 + 128
//       Cr = (128R − 107G − 21B) >> 8 + 128
//   展开成无符号 16 位（**先加偏置再逐项相减**，被减项都非负且之后不再加
//   ⇒ 运行值 ≥ 最终值 ≥ 128，不会下溢）：
//       Cb_raw = (B<<7) + 32768 − 43R − 85G
//       Cr_raw = (R<<7) + 32768 − 107G − 21B
//   系数分解（严格等式）：43=32+8+2+1  85=64+16+4+1  107=64+32+8+2+1  21=16+4+1
//
//   为什么不用直接 RGB 阈值：Cb/Cr **与亮度无关** ⇒ 对光照变化（P6 会改 AE）
//   稳健得多。实测参考点（8 bit）：
//       橙(255,128,0) Cb= 42 Cr=202      白/灰        Cb=128 Cr=128
//       红(255,  0,0) Cb= 85 Cr=255      蓝(0,0,255)  Cb=255 Cr=107
//       黄(255,255,0) Cb=  0 Cr=148      肤色(200,150,120) Cb=104 Cr=155
//   ⇒ 默认判据 `Cb <= 115 且 Cr >= 160` 抓到橙/红，排除白灰蓝黄，**也排除肤色**。
//
//  ---------------------------------------------------------------------------
//  ★ 包围框用"增量"求，不需要 144×8 的计数器阵列
//  ---------------------------------------------------------------------------
//   每个 tile 行只用 **16 个**列计数器（1280/80 = 16）。某列计数**首次越过阈值**
//   的那一拍，直接用 (tile_x, tile_y) 更新全帧 min/max。于是：
//     · 不需要 1,296 FF 的标志阵列，也不需要帧末扫描 FSM；
//     · 噪声抑制仍在（一个 tile 要攒够 TILE_HIT_TH 个命中像素才合格）。
//
//  ★ 每拍 4 像素恰好落在同一个 tile 列
//     80 是 4 的整数倍 ⇒ 第 b 拍 4 个像素 x = 4b..4b+3 的 x/80 全相同
//     ⇒ 每拍只对一个列计数器做一次加法，不需要按像素拆地址。
//
//  ★ 帧结算时机：`I_tuser`（下一帧帧首）
//     用"下一帧帧首"结算上一帧，而不是等帧末 —— 这样 O_* 在整个帧周期内
//     都稳定，跨域乒乓随时可取样。与 `cartoon_96` 用 tuser 复位同一套约定。
//
//  ★ 已知边界（诚实记录，不假装支持）
//     形状分类只用**长宽比**区分 BAR（长条）/ BLOCK（块）。
//     圆形 vs 方形需要看首/末 tile 行的弦宽或四角，**本版未实现** ⇒
//     圆和方都会判成 BLOCK。要支持就把每个 tile 行的合格 x 范围也记下来。
//
//  ★ 输出语义提醒
//     `O_tile_cnt` 是**合格 tile 数**（噪声抑制后的像素面积代理），
//     **不是目标个数** —— 真正的个数需要连通域标记，本版刻意不做。
//     OSD 上必须按它的真实含义标注，不要写成 "N=" 冒充目标计数。
// ============================================================================
`timescale 1ns/1ps

module target_detect_96 #(
    parameter integer IMG_WIDTH     = 1280,
    parameter integer IMG_HEIGHT    = 720,
    parameter integer TILE_PX       = 80,       // tile 边长（像素），需整除宽高
    //  ★ 2026-09-27：12 -> 512。为什么不是随便调大：
    //    真实橙色物体是**成片**的（满铺一个 tile = 6400 个命中像素）；
    //    暗光（L≈32、AG=89）下的色度噪声是**零星**的（约 0.1% ≈ 6 个）。
    //    512 = 6400 的 8%，正好落在"成片"与"零星"之间 ⇒ 挡噪声、放物体。
    //    ⚠ 改了它**必须同时加宽 hit_col**（见下方），否则门槛 >255 会永不达标。
    parameter [12:0]  TILE_HIT_TH   = 13'd512,   // tile 内命中像素数下限（噪声抑制）
    // ★★ 2026-09-26 实测修正：`CR_MIN` 由 160 降到 **146**，并新增 `CB_MIN=30`
    // ----------------------------------------------------------------------------
    //  现象（用户上板）：**手机上的亮橙照片能认出，普通橙色臂章认不出**。
    //  算一遍就清楚：
    //     手机亮橙 (255,128,0)  Cb= 42 Cr=**202**  ✅
    //     哑光臂章 (170,125,100) Cb=107 Cr=**152**  ❌ 差 8 就被 160 挡掉
    //     更暗的橙 (150,115, 95) Cb=104 Cr=**147**  ❌
    //     肤色     (200,150,120) Cb=104 Cr=**155**  ← 当初设 160 就是为了挡它
    //  也就是说：**160 这个门槛把"普通室内光下的哑光橙"和肤色一起挡掉了**。
    //
    //  为什么原来不敢降：**黄色 (255,255,0) 的 Cr = 148** 也正好在门槛附近，
    //  降下来会把黄色放进来。但黄色真正的特征是 **Cb ≈ 0**（很蓝的负向），
    //  而橙色的 Cb 落在 40~107。⇒ 用 `Cb >= CB_MIN(30)` 挡黄色，比用 Cr 挡干净得多：
    //     黄   Cb=  0 ⇒ 被 CB_MIN 挡住（与 Cr 门槛无关）✅
    //     橙   Cb= 42~107 ⇒ 通过 ✅
    //     红   Cb= 85    ⇒ 通过 ✅（红也算暖色，本来就要认）
    //     白/灰 Cb=128   ⇒ 被 CB_MAX 挡住 ✅
    //
    //  ⚠ **诚实说明一个改不掉的限制**：哑光橙 (Cr=152) 与肤色 (Cr=155)
    //     在 Cb/Cr 平面上几乎重合（Cb 107 vs 104），**任何矩形/线性判据都无法分开**。
    //     它们是同一色调、饱和度重叠的颜色。所以现在：
    //        · **哑光橙能被认出来**（这是赛题要的：认出指定目标）
    //        · **手/脸也会被认出来**（这是代价，必须如实说明）
    //     若要恢复"排肤色"，把 `CR_MIN` 改回 160 即可 —— 但哑光橙就又认不出了。
    //     **二者不可兼得**，这一点写进报告，不粉饰。
    parameter [7:0]   CB_MIN        = 8'd30,    // 暖色判据①：Cb >= CB_MIN（挡黄色，Cb≈0）
    parameter [7:0]   CB_MAX        = 8'd115,   //              Cb <= CB_MAX（挡白/灰/蓝）
    parameter [7:0]   CR_MIN        = 8'd146,   //              Cr >= CR_MIN（哑光橙 147~152 可过）
    // ---- ★★ 暖色判据③：**比值判据**（2026-09-26 第二次上板反馈后新增）----
    //   现象：**臂章亮着能认、一按暗就不认**；手臂仍不误检。
    //
    //   根因（这次是我判据的**结构性缺陷**，不是门槛没调好）：
    //     `Cr − 128 = (128R − 107G − 21B) / 256` 是**色差幅度**，
    //     而漫反射下 R/G/B 都正比于照度 E ⇒ **色差幅度也正比于 E**。
    //     同一个橙色布：
    //        亮 (170,125,100) → 128R−107G−21B = 6285 → Cr−128 = **24.5**  ✅ 过 18
    //        暗 ( 85, 62, 50) → 3142       → Cr−128 = **12.3**  ❌ 差 6
    //     ⇒ **"Cb/Cr 与亮度无关"这句话只在"除以亮度之后"才成立**。
    //       我原来直接拿 `Cr` 比固定门槛，等价于**同时比较了颜色和亮度**，
    //       所以一变暗就失效。（这条要写进报告，纠正我之前的说法。）
    //
    //   修法：把亮度除掉 —— 用 `(Cr−128) / G` 当判据（G 是现成的、最省的亮度代理）：
    //        橙  布 (170,125,100) → 24.5/125 = **0.196**
    //        橙  布 ( 85, 62, 50) → 12.3/ 62 = **0.198**  ← **变暗后不变** ✓
    //        肤  色 (200,150,120) → 27.5/150 = **0.183**
    //        肤  色 (140,105, 84) → 19.2/105 = **0.183**  ← 也不变 ✓
    //        纯  黄 (255,255,  0) → 20.9/255 = 0.082 ✓ 排除
    //        白/灰                → 0       ✓ 排除
    //     ⇒ 比值把"亮/暗"这条干扰轴消掉了，橙色族(≈0.196)与肤色(≈0.183)才分得开。
    //
    //   实现（**零乘法**，全部移位加法）：
    //        (Cr−128) > (NUM/256)·G   ⟺   cr_raw > NUM·G + 32768
    //        49·G = (G<<5) + (G<<4) + G
    //   ⚠ **余量很薄，如实说明**：0.196 vs 0.183 只差 ~7%，门槛 49/256=0.1914 取在中间，
    //     两侧各留 ~4%。它是"同色调、饱和度重叠"这一固有事实的代价 ——
    //     换肤色深浅或橙色深浅都可能翻过去，现场按需微调 `CR_RATIO_NUM`。
    parameter [7:0]   CR_RATIO_NUM  = 8'd49,    // 判据③：(Cr−128)/G > NUM/256
    // ---- ★ 暖色判据②（过曝兜底，2026-09-23 加上板照片证据后新增）----
    //   条件：R >= R_CLIP 且 (R-G) >= RG_MARGIN 且 (R-B) >= RB_MARGIN
    //   为什么需要它：曝光顶到上限时三通道一起趋近 255，色度被压平，
    //   判据① 的 Cr 会从 202 掉到 142（< CR_MIN）⇒ 判不出来。
    //   实测：这才是"屏幕上明明是橙色、诊断行却 W 00000"的真因。
    parameter [7:0]   R_CLIP        = 8'd250,   // "R 已经贴顶"的门槛
    parameter [7:0]   RG_MARGIN     = 8'd16,    // R 至少比 G 高这么多
    parameter [7:0]   RB_MARGIN     = 8'd24,    // R 至少比 B 高这么多
    parameter integer BAR_RATIO_X2  = 5,        // 长宽比 >= 2.5 ⇒ BAR（用 2 倍比避免除法）
    // ★ 帧相位对齐开关（1=用 I_tuser 把拍数对齐到真实帧首，见下方"帧相位对齐"）
    //   设 0 可退回"纯自计时"（复位相位任意）—— 留作对照/回退。
    parameter integer ALIGN_ON_TUSER = 1
)(
    input  wire        I_clk,
    input  wire        I_rst_n,

    input  wire        I_tlast,      // ⚠ 现已**刻意不用**（见下方"自计时"说明）
    input  wire        I_tuser,      // ⚠ 同上；保留端口只为与同级模块接口一致
    input  wire [95:0] I_tdata,
    input  wire        I_tvalid,
    input  wire        I_tready,

    // ---- 每帧一组结果（tuser 时更新，帧内保持稳定）----
    output reg  [10:0] O_x_min,      // 包围框（像素坐标，含端点）
    output reg  [10:0] O_x_max,
    output reg  [9:0]  O_y_min,
    output reg  [9:0]  O_y_max,
    output reg  [7:0]  O_tile_cnt,   // 合格 tile 数（**不是**目标个数）
    output reg  [1:0]  O_shape,      // 0=NONE 1=BAR 2=BLOCK
    output reg         O_valid,      // 本帧是否有目标
    output reg         O_frame_start,// 帧结算单拍（跨域握手用）

    // ---- ★ 给 OSD 用的十进制位（**刻意在本模块/本域算**）----
    //  为什么不在 hdmi_mixer 里做：P3 的教训 —— 帧率信号直接进"像素级组合云"
    //  会把 HDMI 域时序拉垮（当时 LATENCY 的除法链把该域 Fmax 压到 76.99 MHz）。
    //  这里在 ISP 域（60 MHz，余量 +17.7%）用比较链算，HDMI 域只做"槽位→字符码"查表。
    //  ⚠ 全程**无除法、无 `*`**：千位一次比较；百/十位比较链；个位 `余数 − 10·十位`。
    output reg  [3:0]  O_x_min_d3,   // 千
    output reg  [3:0]  O_x_min_d2,   // 百
    output reg  [3:0]  O_x_min_d1,   // 十
    output reg  [3:0]  O_x_min_d0,   // 个
    output reg  [3:0]  O_y_min_d2,   // 百（y < 720 ⇒ 不需要千位）
    output reg  [3:0]  O_y_min_d1,   // 十
    output reg  [3:0]  O_y_min_d0,   // 个
    // ---- ★★ 临时诊断输出（上板定位用；定位完连同 OSD 那一行一起删掉）----
    //   板子上"永远显示 NONE"有两种**完全不同的**原因，屏上表现却一模一样：
    //     (A) 颜色判据从不成立（真实光照/AWB 把橙色洗白）
    //     (B) 跨域捕获从未发生（S_tgt_*_h 一直是复位值 0）
    //   ⇒ 把检测器内部的数字直接送到 OSD 上看：
    //        O_dbg_beat_k : 本帧处理的拍数 ÷ 1024（流正常时应 = 225 = 0xE1）
    //        O_dbg_warm   : 本帧"暖色"像素总数（判据成立的像素数）
    //        O_dbg_cb/cr  : 帧中心附近一个探测像素的 Cb/Cr（用来按实际光照定阈值）
    output reg  [7:0]  O_dbg_beat_k,
    output reg  [19:0] O_dbg_warm,
    output reg  [7:0]  O_dbg_cb,
    output reg  [7:0]  O_dbg_cr
);

    // ================================================================ 常量
    localparam integer TILE_COLS     = IMG_WIDTH  / TILE_PX;        // 16
    localparam integer TILE_ROWS     = IMG_HEIGHT / TILE_PX;        // 9
    localparam integer BEAT_PER_TILE = TILE_PX >> 2;                // 20 拍/tile 列

    // ================================================================ 输入像素
    wire [7:0] p0_r = I_tdata[95:88], p0_g = I_tdata[87:80], p0_b = I_tdata[79:72];
    wire [7:0] p1_r = I_tdata[71:64], p1_g = I_tdata[63:56], p1_b = I_tdata[55:48];
    wire [7:0] p2_r = I_tdata[47:40], p2_g = I_tdata[39:32], p2_b = I_tdata[31:24];
    wire [7:0] p3_r = I_tdata[23:16], p3_g = I_tdata[15:8], p3_b = I_tdata[7:0];

    // ================================================================ 色度（零 DSP）
    function [15:0] chroma_cb;              // 128*B − 43*R − 85*G + 32768
        input [7:0] r, g, b;
        reg [15:0] s;
        begin
            s = {9'd0, b} << 7;
            s = s + 16'd32768;
            s = s - ( ({11'd0,r} << 5) + ({11'd0,r} << 3) + ({11'd0,r} << 1) + {11'd0,r} );
            s = s - ( ({11'd0,g} << 6) + ({11'd0,g} << 4) + ({11'd0,g} << 2) + {11'd0,g} );
            chroma_cb = s;
        end
    endfunction

    function [15:0] chroma_cr;              // 128*R − 107*G − 21*B + 32768
        input [7:0] r, g, b;
        reg [15:0] s;
        begin
            s = {9'd0, r} << 7;
            s = s + 16'd32768;
            s = s - ( ({11'd0,g} << 6) + ({11'd0,g} << 5) + ({11'd0,g} << 3)
                    + ({11'd0,g} << 1) + {11'd0,g} );
            s = s - ( ({11'd0,b} << 4) + ({11'd0,b} << 2) + {11'd0,b} );
            chroma_cr = s;
        end
    endfunction

    // ---- 单像素"暖色目标"判决（★ 2026-09-23 增加第二条判据，见下）----
    //  ⚠ 不能对函数返回值直接做位选（`f(x)[15:8]` 不是合法 Verilog-2001），
    //    必须经中间变量。
    //
    //  ★★ 为什么要两条判据（**上板照片定位，2026-09-23**）：
    //     照片上画面正中是一大块饱和橙色物体，而 OSD 诊断行读到 **`W 00000`**
    //     （全画面零个暖色像素），同时 **曝光与增益都顶在最大值**
    //     （`A 07C6 G 59` = AE 1990 / AG 89）、平均亮度 `L 93`(=147) 远高于目标 112。
    //
    //     根因链：**AE 把画面推到过曝 ⇒ 三个通道一起顶到 255 附近 ⇒ 色度被压平**
    //       · 饱和橙 (255,128,  0) → Cr = 202  ✅ 暖
    //       · 过曝橙 (255,230,200) → Cr = (128·255−107·230−21·200)>>8+128
    //                                = (32640−24610−4200)>>8+128 = 14+128 = **142**
    //                                ⇒ 142 < CR_MIN(160) ⇒ **判不出来** ❌
    //     也就是说：**判据本身没错，是"过曝把颜色洗掉了"**。
    //     治本当然是把曝光修对（`ae_ctrl` 的钳位 bug 已修），但为了
    //     "以后哪怕画面偏亮也还能认"，再加一条**对过曝免疫**的判据：
    //
    //         R 已经贴顶（R >= R_CLIP）**且** R 明显高于 G 与 B
    //
    //     为什么它有效、而且**不会把原来排除掉的东西放进来**：
    //       · 过曝橙 (255,230,200)：R 贴顶 ✓、R−G=25 ✓、R−B=55 ✓ ⇒ **暖** ✅
    //       · 白  (255,255,255)：R−G=0 ⇒ ✗（且 Cr=128 也不满足）✅
    //       · 黄  (255,255,  0)：R−G=0 ⇒ ✗ ✅
    //       · 蓝  (  0,  0,255)：R 不贴顶 ⇒ ✗ ✅
    //       · 肤色(200,150,120)：R=200 < R_CLIP ⇒ **不走这条**，仍由 Cr=155<160 排除 ✅
    //     关键点：**R 贴顶**这个前提把"肤色/白/黄"全挡在门外 —— 它们只有在
    //     真正过曝（R=255）时才会进来，而那时 Cr 判据已经失效，正需要它兜底。
    //
    //     ⚠ 诚实边界：过曝到"橙与白都变成 255"时，任何颜色判据都无法区分
    //       （信息已经在传感器端丢失）。这条判据能救的是"R 顶了但 G/B 还没顶"。
    function warm_pix;
        input [7:0] r, g, b;
        reg [15:0] s_cb, s_cr;
        reg [7:0]  cb, cr;
        reg        by_chroma, by_clip, by_ratio;
        begin
            s_cb = chroma_cb(r, g, b);
            s_cr = chroma_cr(r, g, b);
            cb   = s_cb[15:8];
            cr   = s_cr[15:8];
            //  判据①：YCbCr 矩形阈值（正常曝光下最可靠，与亮度无关）
            //   ⚠ Cb 的**下限**（CB_MIN=30）是 2026-09-26 加的：它专门挡黄色
            //     （黄 Cb≈0），这样 Cr 门槛才能从 160 降到 146 去认哑光橙。
            by_chroma = (cb >= CB_MIN) && (cb <= CB_MAX) && (cr >= CR_MIN);
            //  判据②：R 贴顶 + R 明显压制 G/B（**过曝兜底**）
            //   ⚠ 必须写成 `r >= g + MARGIN` 而不是 `(r-g) >= MARGIN`：
            //     后者在 r<g 时 8 位**下溢**成一个很大的数，比较会**误判为真**
            //     （白/黄都是 r==g，会被错误地放进来）。加宽到 9 位再比即可。
            by_clip   = (r >= R_CLIP)
                     && ({1'b0, r} >= ({1'b0, g} + {1'b0, RG_MARGIN}))
                     && ({1'b0, r} >= ({1'b0, b} + {1'b0, RB_MARGIN}));
            //  判据③：**比值判据**（对"变暗"免疫，见参数区注释）
            //     (Cr−128) > (NUM/256)·G  ⟺  cr_raw > NUM·G + 32768
            //     NUM=49 ⇒ 49·G = (G<<5)+(G<<4)+G（移位加法，无乘法）
            //
            //  ★★ 这里**刻意不加 Cb 的绝对上下限**（第一版加了，结果是变暗的橙色
            //     反而判不出来）：
            //     `Cb−128` 与 `Cr−128` 一样**正比于色差幅度**，也随幅度缩小：
            //        亮臂章 (170,125,100) → Cb = 107  （≤115 ✓ 在范围内）
            //        暗臂章 ( 85, 62, 50) → Cb = **118**（>115 ✗ **被误挡**！因为变暗后
            //                              Cb 趋向中性 128）
            //     ⇒ 在"比值"判据里再用绝对 Cb 门槛，等于把刚除掉的那个干扰轴又加回来。
            //     而 `Cr/G` 比值本身已经把黄(0.082)/白(0)/灰(0)/蓝(负) 全部排除了
            //     （它们的比值都远低于门槛），不需要 Cb 帮忙。
            by_ratio  = (s_cr > (({8'd0, g} << 5) + ({8'd0, g} << 4) + {8'd0, g}
                                 + 16'd32768));
            warm_pix  = by_chroma || by_clip || by_ratio;
        end
    endfunction

    wire [2:0] beat_hits = { 2'd0, warm_pix(p0_r,p0_g,p0_b) }
                         + { 2'd0, warm_pix(p1_r,p1_g,p1_b) }
                         + { 2'd0, warm_pix(p2_r,p2_g,p2_b) }
                         + { 2'd0, warm_pix(p3_r,p3_g,p3_b) };

    // ================================================================ 行列计数
    reg [4:0]  col_in_tile;     // 0..BEAT_PER_TILE-1
    reg [3:0]  tile_x;          // 0..TILE_COLS-1
    reg [6:0]  line_in_tile;    // 0..TILE_PX-1
    reg [3:0]  tile_y;          // 0..TILE_ROWS-1

    // ---- 当前 tile 行的 16 个列命中计数器（饱和）----
    reg [12:0] hit_col [0:15];   // ★ 13 位（原 8 位饱和 255，撑不住 512 门槛）

    // ================================================================ 本周期的"有效位置"
    //  ★★ 踩坑（2026-09-21，由 Python 独立模型抓出）：
    //     `tuser` 那一拍**本身就是新帧的第 0 拍**。第一版只"复位计数器"、
    //     却没把这拍算进 (0,0)（而且它的累加还被 tuser 分支的清零覆盖掉）
    //      ⇒ 列计数**永久错开一拍** ⇒ 每个 tile 会吃到右邻居的 4 个像素。
    //     目标高 160 行时，邻居 tile 白拿 4×80=320 个命中 ≫ 阈值 12，
    //     于是**左边多出一个假 tile**（实测 x_min=240 而非期望 320、tiles=6 而非 4）。
    //   ⇒ 用 P_* 把"帧首强制回到 (0,0)"表达出来，并且**让这拍正常参与累加**。
    // ★★ 结构**完全由拍数自计时推导**，不依赖 I_tuser / I_tlast
    // ---------------------------------------------------------------------------
    //  踩坑（2026-09-21 上板，代价是一次诊断构建）：第一版用
    //      `is_ff = I_tvalid && I_tuser`  作为"帧结算"事件、用 `I_tlast` 推进行计数，
    //  上板后**屏上恒显示复位值**（诊断行 `B00 W00000 C00/00` ⇒ 一帧都没结算过）。
    //
    //  根因在 `awb.v`（实测读到）：
    //      awb.v:369  assign O_tlast = (valid_d1==0) && (valid_d2==1);  // 是 valid 上升沿，**不是行尾**
    //      awb.v:370  assign O_tuser = I_tuser;                        // tuser **组合直通**
    //      awb.v:371  assign O_tvalid = valid_d2;                      // 而 tdata/tvalid 有流水延迟
    //  ⇒ 在 awb 输出口上，`tuser` 到达那一拍正好落在**帧间消隐期（tvalid=0）**
    //     ⇒ `is_ff` **永不成立** ⇒ 帧永不结算 ⇒ 所有输出保持复位值。
    //  而且 `O_tlast` 根本不是行尾标记 ⇒ 行计数也永远不推进。
    //
    //  ⇒ 改为与 `cartoon_96` 相同的自计时做法：行/块行/帧边界全部从**拍数**推出
    //     （每行 BEAT_PER_LINE=320 拍、每 tile 行 80 行、每帧 720 行）。
    //     `I_tuser` 只用于"可选对齐"（见下方，默认不启用），`I_tlast` 完全不用。
    //     这一步同时验证了"ISP 流每行确实是 320 拍"——诊断位 `B`（拍数÷1024）会直接显示。
    // ---------------------------------------------------------------------------
    // ===========================================================================
    // ★★ 2026-09-26：**帧相位对齐**（修"红框整体偏下"的真根因）
    // ---------------------------------------------------------------------------
    //  问题：本模块的帧/行边界是**纯拍数自计时**，而拍数从**复位释放**开始数
    //  ⇒ 复位那一刻摄像头正在哪一行，就成了本模块的"第 0 行"。
    //     于是上报的 y 坐标带一个**任意常数偏移**（上板实测：框比目标偏下约 1 个
    //     tile 行以上）。x 同理。（诊断位 `B` 只能证明"每帧 230400 拍"，
    //     证明不了相位对 —— 这正是当初没发现的原因。）
    //
    //  修法：用 `I_tuser`（帧首标记）把计数器**重新对齐**到真实帧首。
    //   ★ 为什么这次可以用 tuser 而不违反铁律四：
    //     铁律四禁止的是把 `I_tvalid && I_tuser` 当"帧结算"条件 —— 因为 awb 的
    //     `O_tuser` 是组合直通、`O_tvalid` 有流水延迟，**两者不同拍**，那个与条件
    //     永不成立。这里只把 tuser 当作"帧首脉冲"用（单比特、每帧一次），
    //     它本身就是真实帧首标记；与数据的流水深度差几拍，只带来
    //     **≤ 几个像素**的固定偏差（远小于原来任意上百行）。
    //
    //   ★★ 关键：对齐那一拍**必须照常参与累加**，不能丢弃。
    //     若丢弃一拍，每帧就少算一拍 ⇒ 帧边界每帧漂移 1 拍（=4 像素），
    //     1 秒就漂 240 像素，画面会越来越歪。
    //     做法：把 P_* 在**对齐那一拍强制为 (0,0)**，让它作为新帧第 0 拍被正常处理。
    //     ⇒ 一拍不丢、不漂移。
    // ===========================================================================
    wire w_align = I_tvalid && I_tuser && (ALIGN_ON_TUSER != 0);

    wire [3:0] P_tile_x = w_align ? 4'd0 : tile_x;
    wire [4:0] P_col    = w_align ? 5'd0 : col_in_tile;
    wire [3:0] P_tile_y = w_align ? 4'd0 : tile_y;
    wire [6:0] P_line   = w_align ? 7'd0 : line_in_tile;

    // ---- 组合量：全部从**寄存器** hit_col / P_tile_x 推出，无求值顺序问题 ----
    //  ★ 13 位：一个 tile 最多 80x80=6400 命中 < 8192 ⇒ **不需要饱和逻辑**，
    //    直接取低位即可（原来 8 位饱和在 255 是个静默陷阱）。
    wire [12:0] hit_cur = hit_col[P_tile_x];
    wire [12:0] hit_sum = hit_cur + {10'd0, beat_hits};
    wire [12:0] hit_new = hit_sum;
    wire       tile_qual_now = (hit_cur < TILE_HIT_TH) && (hit_new >= TILE_HIT_TH);

    // ---- 边界（全部由拍数推出）----
    //   行尾  = 最后一个 tile 列的第 20 拍到达时
    wire       line_end      = I_tvalid && (P_col == BEAT_PER_TILE - 1) &&
                                          (P_tile_x == TILE_COLS - 1);
    wire       tile_row_end  = line_end && (P_line == TILE_PX - 1);
    wire       frame_end     = tile_row_end && (P_tile_y == TILE_ROWS - 1);

    // ================================================================ 全帧包围框累加（tile 坐标）
    reg [3:0]  tx_min, tx_max;      // 0..15
    reg [3:0]  ty_min, ty_max;      // 0..8
    reg [7:0]  t_cnt;
    reg        any_hit;

    // ---- 形状判决（纯比较/移位，无 `*` 无除法）----
    //   tw = tx_max−tx_min+1 (1..16)   th = ty_max−ty_min+1 (1..9)
    //   BAR ⟺ 2·tw >= 5·th  或  2·th >= 5·tw
    wire [4:0] tw = {1'b0, tx_max} - {1'b0, tx_min} + 5'd1;
    wire [4:0] th = {1'b0, ty_max} - {1'b0, ty_min} + 5'd1;
    wire       bar_now = ( {tw, 1'b0} >= ((th << 2) + th) ) ||
                         ( {th, 1'b0} >= ((tw << 2) + tw) );

    // ---- tile 坐标 → 像素坐标（×80 = ×64 + ×16，移位加法）----
    wire [10:0] w_xmin = (tx_min << 6) + (tx_min << 4);
    wire [10:0] w_xmax = (tx_max << 6) + (tx_max << 4) + 11'd79;
    wire [9:0]  w_ymin = (ty_min << 6) + (ty_min << 4);
    wire [9:0]  w_ymax = (ty_max << 6) + (ty_max << 4) + 10'd79;

    // ================================================================ 十进制（比较链，无除法无乘法）
    //  把 0..999 拆成 {百, 十, 个}（12 bit = 3 个 4 bit）
    //    百位：与 900/800/.../100 比较（9 个常数比较器）
    //    十位：对余数再比较 90/80/.../10
    //    个位：余数 − 10·十位   （10 = 8+2，移位加法）
    function [11:0] dec3;
        input [10:0] v;
        reg [3:0]    h, t;
        reg [10:0]   r2, r3;
        begin
            if      (v >= 11'd900) h = 4'd9;
            else if (v >= 11'd800) h = 4'd8;
            else if (v >= 11'd700) h = 4'd7;
            else if (v >= 11'd600) h = 4'd6;
            else if (v >= 11'd500) h = 4'd5;
            else if (v >= 11'd400) h = 4'd4;
            else if (v >= 11'd300) h = 4'd3;
            else if (v >= 11'd200) h = 4'd2;
            else if (v >= 11'd100) h = 4'd1;
            else                   h = 4'd0;
            r2 = v - ( (h << 6) + (h << 5) + (h << 2) );        // −100h（100 = 64+32+4）
            if      (r2 >= 11'd90) t = 4'd9;
            else if (r2 >= 11'd80) t = 4'd8;
            else if (r2 >= 11'd70) t = 4'd7;
            else if (r2 >= 11'd60) t = 4'd6;
            else if (r2 >= 11'd50) t = 4'd5;
            else if (r2 >= 11'd40) t = 4'd4;
            else if (r2 >= 11'd30) t = 4'd3;
            else if (r2 >= 11'd20) t = 4'd2;
            else if (r2 >= 11'd10) t = 4'd1;
            else                   t = 4'd0;
            // ⚠⚠ 位宽陷阱（实测踩过，代价是一次上板前的调试）：
            //   拼接 `{h, t, 表达式}` 的**每个操作数都是"自决定位宽"**。
            //   若把 `r2 - (...)` 直接写进拼接，它含 r2（11 位）⇒ 整个拼接变成
            //   4+4+11 = **19 位**，赋给 12 位的 dec3 时**从左侧截断**，有效位全丢 ⇒
            //   函数恒返回 0（现象：包围框全对、十进制位全是 0）。
            //   ⇒ 必须先落到 11 位的中间变量 r3，再取 4 位切片。
            r3 = r2 - ( (t << 3) + (t << 1) );                  // −10t（10 = 8+2）
            dec3 = { h, t, r3[3:0] };
        end
    endfunction

    // x_min 的千位（0 或 1，因为 x ≤ 1279）；去掉千位后的余数
    wire        x_th   = (w_xmin >= 11'd1000);
    wire [10:0] x_rest = x_th ? (w_xmin - 11'd1000) : w_xmin;
    wire [11:0] x_lo   = dec3(x_rest);      // {百,十,个}
    wire [11:0] y_lo   = dec3(w_ymin);      // y ≤ 719 < 1000 ⇒ 直接用

    integer i;

    // ================================================================ ★ 临时诊断计数（上板定位用）
    reg [17:0] S_beat_cnt;      // 本帧有效拍数
    reg [19:0] S_warm_cnt;      // 本帧暖色像素数（饱和）
    reg [7:0]  S_cb_probe, S_cr_probe;
    //  ★ 2026-09-27：全帧最暖像素跟踪（把诊断探测点从固定点改成自动锁定）
    //    为什么改：探测点原来固定在 tile(4,8) 左上角 = (640,320)。要量一个物体的
    //    颜色必须把它**正好放到画面正中**；两次上板测量都失败（读数 `7C/xx`，
    //    Cb≈124 接近中性 —— 落在暗背景上，没量到目标）。我因此只能拿"我以为的
    //    橙色/肤色"调阈值，颜色判据连改三轮。改成跟踪全帧 Cr 最大的像素后，
    //    物体放任意位置，`C xx/xx` 显示的就是它最暖那一像素的真实色度。
    //    ⚠ 若画面里有比目标更红的过曝高光，会锁到高光上 —— 测量时避开高光。
    reg [15:0] S_cr_max;

    // 探测点：tile 行 4、tile 列 8 的左上角那一拍 ⇒ x=640, y=320（画面中心附近）
    //  ⚠ 2026-09-27 起 `probe_en` **不再使用**（探测点已改为全帧自动锁定）。
    //    保留它只为了留下"原来固定在画面正中"这条历史记录，便于对照两次失败的测量。
    wire       probe_en = I_tvalid && (P_tile_x == 4'd8) && (P_tile_y == 4'd4) &&
                          (P_line == 7'd0) && (P_col == 5'd0);
    wire [15:0] probe_cb16 = chroma_cb(p0_r, p0_g, p0_b);
    wire [15:0] probe_cr16 = chroma_cr(p0_r, p0_g, p0_b);

    // ================================================================ 主时序
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            col_in_tile  <= 5'd0;
            tile_x       <= 4'd0;
            line_in_tile <= 7'd0;
            tile_y       <= 4'd0;
            tx_min <= 4'd0; tx_max <= 4'd0;
            ty_min <= 4'd0; ty_max <= 4'd0;
            t_cnt  <= 8'd0; any_hit <= 1'b0;
            O_x_min <= 11'd0; O_x_max <= 11'd0;
            O_y_min <= 10'd0; O_y_max <= 10'd0;
            O_tile_cnt <= 8'd0;
            O_shape <= 2'd0;
            O_valid <= 1'b0;
            O_frame_start <= 1'b0;
            O_x_min_d3 <= 4'd0; O_x_min_d2 <= 4'd0;
            O_x_min_d1 <= 4'd0; O_x_min_d0 <= 4'd0;
            O_y_min_d2 <= 4'd0; O_y_min_d1 <= 4'd0; O_y_min_d0 <= 4'd0;
            S_beat_cnt <= 18'd0; S_warm_cnt <= 20'd0;
            S_cb_probe <= 8'd0;  S_cr_probe <= 8'd0;  S_cr_max <= 16'd0;
            O_dbg_beat_k <= 8'd0; O_dbg_warm <= 20'd0;
            O_dbg_cb <= 8'd0; O_dbg_cr <= 8'd0;
            for (i = 0; i < 16; i = i + 1) hit_col[i] <= 13'd0;
        end else begin
            O_frame_start <= 1'b0;              // 默认单拍

            if (I_tvalid) begin
                // ---------------- ⓪ ★ 诊断计数（临时）----------------
                S_beat_cnt <= (S_beat_cnt == 18'h3FFFF) ? S_beat_cnt : (S_beat_cnt + 18'd1);
                if (S_warm_cnt + {16'd0, beat_hits} > 20'hFFFFF)
                    S_warm_cnt <= 20'hFFFFF;
                else
                    S_warm_cnt <= S_warm_cnt + {16'd0, beat_hits};
                //  ★ 改动点：原来是 `if (probe_en)`（固定坐标 640,320）。
                //    现在改成**全帧最大值跟踪** —— 每拍比较一次 p0 的 Cr，
                //    更大就锁存它的 Cb/Cr。复位与帧对齐两处都会清 `S_cr_max`，
                //    所以每帧重新找一次当前画面里最暖的像素。
                //    ⚠ 只比较每拍的 p0（4 像素里的第 1 个）⇒ 采样率 1/4。
                //      对"找最暖像素"这种诊断用途足够；全采样要 4 路比较器，不值。
                if (probe_cr16 > S_cr_max) begin
                    S_cr_max   <= probe_cr16;
                    S_cb_probe <= probe_cb16[15:8];
                    S_cr_probe <= probe_cr16[15:8];
                end

                // ---------------- ① 列命中计数器更新 ----------------
                if (tile_row_end || w_align) begin
                    // tile 行末那拍：整行归零。本拍的命中**不需要**写进 hit_col ——
                    // 因为 tile_qual_now 已经用 hit_new 判过一次了（见下方 ②）。
                    // ★ w_align（帧相位对齐那一拍）也整行归零：把"上一帧被打断时的
                    //   半截 tile 计数"丢掉，新帧从干净状态开始。
                    for (i = 0; i < 16; i = i + 1) hit_col[i] <= 13'd0;
                end else begin
                    hit_col[P_tile_x] <= hit_new;
                end

                // ★ 帧相位对齐那一拍：全帧包围框/计数 + 诊断计数器全部清零
                if (w_align) begin
                    tx_min <= 4'd0; tx_max <= 4'd0;
                    ty_min <= 4'd0; ty_max <= 4'd0;
                    t_cnt  <= 8'd0; any_hit <= 1'b0;
                    S_beat_cnt <= 18'd0;
                    S_warm_cnt <= 20'd0;
                    S_cr_max   <= 16'd0;   // ★ 新帧重新找最暖像素
                end

                // ---------------- ② 该 tile 首次达标 ⇒ 更新全帧包围框 ----------------
                //   ⚠ 必须 `!w_align`：对齐那一拍 P_* 被强制成 (0,0)，而 hit_col[0]
                //     还是**上一帧残留**的值，若不禁掉会拿残留值判一次、把刚清零的
                //     t_cnt/tx_* 又写脏（同一 always 块里后写的赋值覆盖前面的）。
                if (tile_qual_now && !w_align) begin
                    t_cnt <= t_cnt + 8'd1;
                    if (!any_hit) begin
                        tx_min <= P_tile_x;  tx_max <= P_tile_x;
                        ty_min <= P_tile_y;  ty_max <= P_tile_y;
                        any_hit <= 1'b1;
                    end else begin
                        if (P_tile_x < tx_min) tx_min <= P_tile_x;
                        if (P_tile_x > tx_max) tx_max <= P_tile_x;
                        if (P_tile_y < ty_min) ty_min <= P_tile_y;
                        if (P_tile_y > ty_max) ty_max <= P_tile_y;
                    end
                end

                // ---------------- ③ 帧末：结算本帧 ----------------
                if (frame_end) begin
                    // ⚠ 无目标时把包围框显式清零（而不是留下 79 的残值）。
                    //   虽然 O_valid=0 时下游不该画框，但接口语义明确更安全。
                    O_x_min    <= any_hit ? w_xmin : 11'd0;
                    O_x_max    <= any_hit ? w_xmax : 11'd0;
                    O_y_min    <= any_hit ? w_ymin : 10'd0;
                    O_y_max    <= any_hit ? w_ymax : 10'd0;
                    O_tile_cnt <= t_cnt;
                    O_valid    <= any_hit;
                    O_shape    <= (!any_hit) ? 2'd0 : (bar_now ? 2'd1 : 2'd2);
                    O_frame_start <= 1'b1;

                    // 十进制位（无目标时显式清零）
                    O_x_min_d3 <= (any_hit && x_th) ? 4'd1 : 4'd0;
                    O_x_min_d2 <= any_hit ? x_lo[11:8] : 4'd0;
                    O_x_min_d1 <= any_hit ? x_lo[7:4]  : 4'd0;
                    O_x_min_d0 <= any_hit ? x_lo[3:0]  : 4'd0;
                    O_y_min_d2 <= any_hit ? y_lo[11:8] : 4'd0;
                    O_y_min_d1 <= any_hit ? y_lo[7:4]  : 4'd0;
                    O_y_min_d0 <= any_hit ? y_lo[3:0]  : 4'd0;

                    // ★ 诊断值锁存 + 计数器清零（临时）
                    O_dbg_beat_k <= S_beat_cnt[17:10];   // ÷1024：流正常时应 = 0xE1 (225)
                    O_dbg_warm   <= S_warm_cnt;
                    O_dbg_cb     <= S_cb_probe;
                    O_dbg_cr     <= S_cr_probe;
                    S_beat_cnt   <= 18'd0;
                    S_warm_cnt   <= 20'd0;

                    // 清全帧累加器（位置计数器由 P_* 在本拍表达为 0，下一拍自然接上）
                    tx_min <= 4'd0; tx_max <= 4'd0;
                    ty_min <= 4'd0; ty_max <= 4'd0;
                    t_cnt  <= 8'd0; any_hit <= 1'b0;
                end

                // ---------------- ④ 列推进（从 P_col/P_tile_x 出发）----------------
                if (P_col == BEAT_PER_TILE - 1) begin
                    col_in_tile <= 5'd0;
                    tile_x      <= (P_tile_x == TILE_COLS - 1) ? 4'd0 : (P_tile_x + 4'd1);
                end else begin
                    col_in_tile <= P_col + 5'd1;
                    tile_x      <= P_tile_x;
                end

                // ---------------- ⑤ 行推进（行尾由拍数判定；tile 行末则回到第 0 行）----------------
                if (line_end) begin
                    if (P_line == TILE_PX - 1) begin
                        line_in_tile <= 7'd0;
                        tile_y <= (P_tile_y == TILE_ROWS - 1) ? 4'd0 : (P_tile_y + 4'd1);
                    end else begin
                        line_in_tile <= P_line + 7'd1;
                        tile_y       <= P_tile_y;
                    end
                end else begin
                    line_in_tile <= P_line;
                    tile_y       <= P_tile_y;
                end
            end
        end
    end

