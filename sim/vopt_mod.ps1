# ============================================================
#  vopt_mod.ps1 -- 对任意模块做 vopt 结构检查（不需要许可证）
#
#  为什么有用：
#     vsim 需要许可证，vopt 不需要。vopt 会做真正的 elaboration
#     （加载模块、解析端口连接、检查位宽、展开层次、inlining），
#     足以在**没有仿真器**的情况下排除结构性错误。
#
#  (!) 不能替代功能仿真。结论只能表述为"结构检查通过"。
#
#  设计要点（都是踩过的坑）：
#     1) 端口名**从源文件自动提取**，不靠参数传入
#        —— 早期版本用参数传端口数组，PowerShell 的 -File 绑定
#           与逗号拆分反复出问题，自动提取彻底消除该风险。
#     2) 安路原语库用 +define+FORMAL_VERIFICATION 编译
#        —— 否则 al_map_basic.v 引用 glbl.gsrn，vopt 报 vopt-7052。
#     3) 顶层例化 glbl / PH1P_PHY_GSR，实例名必须正好是模块名。
#     4) vopt 的 -modelsimini 必须在 designUnit 之前。
#     5) Verilog 反引号用 [char]96 生成，避免 PowerShell 吞掉 timescale。
#
#  用法：
#     powershell -ExecutionPolicy Bypass -File .\sim\vopt_mod.ps1 `
#         -TopFile <path\to\mod.v> [-TopModule name] [-Deps "a.v,b.v"]
# ============================================================
[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$TopFile,
    [string]$TopModule = '',
    [string]$Deps      = '',
    [string]$Params    = '',
    [string]$ModelRoot = 'F:\model',
    [string]$TdRoot    = 'F:\al',
    [string]$OutDir    = ''
)

$ErrorActionPreference = 'Stop'
$bin    = Join-Path $ModelRoot 'win64'
$vlib   = Join-Path $bin 'vlib.exe'
$vlog   = Join-Path $bin 'vlog.exe'
$vmap   = Join-Path $bin 'vmap.exe'
$vopt   = Join-Path $bin 'vopt.exe'
$simRel = Join-Path $TdRoot 'sim_release'

foreach ($p in @($vlib,$vlog,$vmap,$vopt)) { if (-not (Test-Path $p)) { throw "缺少 $p" } }

if (-not (Test-Path $TopFile)) { throw "找不到 $TopFile" }
$TopFileAbs = (Resolve-Path $TopFile).Path
if (-not $TopModule) { $TopModule = [IO.Path]::GetFileNameWithoutExtension($TopFileAbs) }
if (-not $OutDir)    { $OutDir = Join-Path $PSScriptRoot 'voptmod' }
if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Force -Path $OutDir | Out-Null }
$OutDir = (Resolve-Path $OutDir).Path

$depList = @()
if ($Deps) { foreach ($d in ($Deps -split ',')) { $d = $d.Trim(); if ($d) { $depList += (Resolve-Path $d).Path } } }
$paramList = @()
if ($Params) { foreach ($q in ($Params -split ',')) { $q = $q.Trim(); if ($q) { $paramList += $q } } }

Write-Host "== 顶层文件 : $TopFileAbs"
Write-Host "== 顶层模块 : $TopModule"
Write-Host "== 依赖     : $(if($depList.Count){$depList -join ', '}else{'(无)'})"

# ---------------------------------------------------------------- 端口自动提取
$srcText = [IO.File]::ReadAllText($TopFileAbs)
$inputs  = New-Object System.Collections.Generic.List[string]
$outputs = New-Object System.Collections.Generic.List[string]
$rx = [regex]("module\s+" + [regex]::Escape($TopModule) + "\s*(#\s*\([^)]*\))?\s*\((.*?)\)\s*;")
$mDecl = $rx.Match($srcText, [Text.RegularExpressions.RegexOptions]::Singleline)
if ($mDecl.Success) {
    $body = $mDecl.Groups[2].Value
    $body = [regex]::Replace($body, '//[^\r\n]*', '')
    $body = [regex]::Replace($body, '/\*.*?\*/', '', [Text.RegularExpressions.RegexOptions]::Singleline)
    $kw = @('input','output','inout','wire','reg','signed','unsigned','logic','bit')
    foreach ($item in ($body -split ',')) {
        $it = $item.Trim()
        if (-not $it) { continue }
        $target = $null
        if     ($it -match '^input\b')  { $target = $inputs }
        elseif ($it -match '^output\b') { $target = $outputs }
        if ($target) {
            foreach ($nm in [regex]::Matches($it, '[A-Za-z_]\w*')) {
                if ($nm.Value -notin $kw) { $target.Add($nm.Value) }
            }
        }
    }
}
if ($inputs.Count -eq 0 -and $outputs.Count -eq 0) {
    Write-Host "   (未提取到端口，做无端口连接的结构检查)" -ForegroundColor Yellow
} else {
    Write-Host "   自动提取端口: in=$($inputs.Count) out=$($outputs.Count)"
}

# ---------------------------------------------------------------- 生成 wrapper
$BT = [char]96
$L  = New-Object System.Collections.Generic.List[string]
$L.Add('// auto-generated by sim/vopt_mod.ps1')
$L.Add("${BT}timescale 1ns/1ps")
$L.Add("module vopt_wrap_$TopModule;")
$L.Add('    glbl         glbl();')
$L.Add('    PH1P_PHY_GSR PH1P_PHY_GSR();')
$L.Add('')
$L.Add("    reg I_clk = 1'b0;")
$L.Add('    always #5 I_clk = ~I_clk;')
$L.Add('')

$declLines = New-Object System.Collections.Generic.List[string]
$connLines = New-Object System.Collections.Generic.List[string]
foreach ($p in $inputs) {
    if ($p -eq 'I_clk') { $connLines.Add("        .$p(I_clk)"); continue }
    $declLines.Add("    reg  $p;")
    $connLines.Add("        .$p($p)")
}
foreach ($p in $outputs) {
    $declLines.Add("    wire $p;")
    $connLines.Add("        .$p($p)")
}
foreach ($d in $declLines) { $L.Add($d) }
$L.Add('')

if ($paramList.Count) {
    $L.Add("    $TopModule #(")
    for ($i = 0; $i -lt $paramList.Count; $i++) {
        $kv = $paramList[$i] -split '=', 2
        $suffix = if ($i -lt $paramList.Count - 1) { ',' } else { '' }
        $L.Add("        .$($kv[0].Trim())($($kv[1].Trim()))$suffix")
    }
    $L.Add('    ) u_dut(')
} else {
    $L.Add("    $TopModule u_dut(")
}
for ($i = 0; $i -lt $connLines.Count; $i++) {
    $suffix = if ($i -lt $connLines.Count - 1) { ',' } else { '' }
    $L.Add($connLines[$i] + $suffix)
}
$L.Add('    );')
$L.Add('endmodule')

$wrapper = Join-Path $OutDir "_wrap_$TopModule.v"
Set-Content -Path $wrapper -Value ($L -join "`r`n") -Encoding ASCII
Write-Host "== wrapper  -> $wrapper"

Push-Location $OutDir
try {
    foreach ($l in @('work','gf_common','gf_ph1p')) { if (-not (Test-Path $l)) { & $vlib $l | Out-Null } }
    & $vmap work      ./work      *> $null
    & $vmap gf_common ./gf_common *> $null
    & $vmap gf_ph1p   ./gf_ph1p   *> $null

    if (-not (Test-Path (Join-Path $OutDir 'gf_common\glbl'))) {
        Write-Host "== 编译安路原语库（约 25s）..." -ForegroundColor Cyan
        $c = @()
        $c += Get-ChildItem (Join-Path $simRel 'common\*.v')     -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName }
        $c += Get-ChildItem (Join-Path $simRel 'common\apm\*.v') -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName }
        & $vlog -quiet +define+FORMAL_VERIFICATION -work gf_common @c *> $null
        if ($LASTEXITCODE -ne 0) { throw "gf_common 编译失败" }
        $ph = Get-ChildItem (Join-Path $simRel 'ph1p\*.v') -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName }
        & $vlog -quiet +define+FORMAL_VERIFICATION -work gf_ph1p @ph *> $null
        if ($LASTEXITCODE -ne 0) { throw "gf_ph1p 编译失败" }
    }

    Write-Host "== 编译设计与 wrapper ..." -ForegroundColor Cyan
    $files = @()
    if ($depList.Count) { $files += $depList }
    $files += $TopFileAbs
    $files += $wrapper
    $o1 = & $vlog -quiet +define+FORMAL_VERIFICATION -work work @files 2>&1
    $rc1 = $LASTEXITCODE
    if ($rc1 -ne 0) {
        $o1 | Where-Object { $_ -match '\*\* Error' } | Select-Object -First 10 | ForEach-Object { Write-Host "   $_" -ForegroundColor Red }
        Write-Host "vlog 编译失败（exit $rc1）" -ForegroundColor Red
        exit 2
    }

    Write-Host "== vopt 详细化 ..." -ForegroundColor Cyan
    $o2 = & $vopt -L gf_common -L gf_ph1p "work.vopt_wrap_$TopModule" -o "opt_$TopModule" 2>&1
    $rc2 = $LASTEXITCODE

    $errs   = @($o2 | Where-Object { $_ -match '\*\* Error' })
    $warns  = @($o2 | Where-Object { $_ -match '\*\* Warning' })
    $loaded = @($o2 | Where-Object { $_ -match '^-- Loading module' })
    $inl    = @($o2 | Where-Object { $_ -match '^-- Inlining module' })

    Write-Host ''
    Write-Host '=============== vopt 结构检查结果 ===============' -ForegroundColor Green
    Write-Host ("  模块           : {0}" -f $TopModule)
    Write-Host ("  退出码         : {0}" -f $rc2)
    Write-Host ("  加载 / inlining : {0} / {1}" -f $loaded.Count, $inl.Count)
    Write-Host ("  Error          : {0}" -f $errs.Count)
    Write-Host ("  Warning        : {0}" -f $warns.Count)
    if ($warns.Count -gt 0) {
        Write-Host '  --- Warning 去重（前 10）---' -ForegroundColor Yellow
        $warns | ForEach-Object { $_ -replace '^\*\* Warning:\s*','' } | Sort-Object -Unique |
            Select-Object -First 10 | ForEach-Object { Write-Host "    $_" }
    }
    Write-Host ''
    if ($rc2 -eq 0) {
        Write-Host '  [PASS] 结构检查通过' -ForegroundColor Green
        Write-Host '         (不等于功能正确；功能需 vsim 或上板)' -ForegroundColor Yellow
    } else {
        Write-Host '  [FAIL] 结构检查失败' -ForegroundColor Red
        $errs | Select-Object -First 10 | ForEach-Object { Write-Host "    $_" }
    }
    Write-Host '================================================' -ForegroundColor Green
    exit $(if ($rc2 -eq 0) { 0 } else { 1 })
}
finally { Pop-Location }
