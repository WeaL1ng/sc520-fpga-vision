# 1. 从原文件提取现有字形（必须逐位保留）
# ---------------------------------------------------------------------------
src = LIB.read_text(encoding="utf-8", errors="replace")

consts = {}
for m in re.finditer(r"localparam\s+(CHAR_\w+)\s*=\s*8'h([0-9a-fA-F]{2})\s*;", src):
    consts[m.group(1)] = int(m.group(2), 16)

existing = {}
for m in re.finditer(r"(CHAR_\w+)\s*:\s*begin(.*?)endcase\s*end", src, re.S):
    name, body = m.group(1), m.group(2)     # name 含 CHAR_ 前缀
    rows = {}
    for rm in re.finditer(r"4'd(\d+)\s*:\s*O_row_bits\s*=\s*16'h([0-9a-fA-F]{4})", body):
        rows[int(rm.group(1))] = int(rm.group(2), 16)
    if rows:
        existing[name] = rows

print("原文件: %d 个 CHAR_ 常量, %d 个已解析字形" % (len(consts), len(existing)))
if len(existing) != len(consts):
    print("!! 解析字形数与常量数不一致，中止（避免写坏原有字形）")
    sys.exit(1)

# ---------------------------------------------------------------------------
# 2. 合并
# ---------------------------------------------------------------------------
