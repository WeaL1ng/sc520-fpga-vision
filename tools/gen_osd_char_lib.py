def art_to_bits(lines):
    """ASCII 图 -> 16 个 16bit 整数

    ASCII 图第 0 行写入点阵的 row = ART_TOP_ROW（默认 2），
    以对齐原版大写字母的行范围（row 2..9）。
    """
    assert len(lines) == ART_LINES, "字形应为 %d 行，实际 %d" % (ART_LINES, len(lines))
    out = [0] * ROWS
    for i, s in enumerate(lines):
        assert len(s) <= WIDTH, "行宽超限(%d): %r" % (len(s), s)
        v = 0
        for c, ch in enumerate(s):
            if ch == '#':
                v |= 1 << (WIDTH - 1 - c)
        r = ART_TOP_ROW + i
        if r < ROWS:
            out[r] = v
    return out


