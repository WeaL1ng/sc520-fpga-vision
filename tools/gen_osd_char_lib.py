for name, code in consts.items():
    rows = existing[name]
    final[code] = (name, [rows.get(r, 0) for r in range(ROWS)])

# 标点/符号 -> 合法 Verilog 标识符后缀（**必须逐个列出**，
# 否则会生成 `CHAR_(` 这类非法标识符，且解析器扫不到）
SYMBOL_NAMES = {
    ' ': "SP",
    '.': "DOT",
    '-': "MINUS",
    '/': "SLASH",
    '%': "PCT",
    '(': "LPAREN",
    ')': "RPAREN",
    '+': "PLUS",
    ',': "COMMA",
    '<': "LT",
    '=': "EQ",
    '>': "GT",
}


def make_name(ch):
    if ch in SYMBOL_NAMES:
        return "CHAR_" + SYMBOL_NAMES[ch]
    if ch.isalpha() and ch.islower():
        return "CHAR_LOW_" + ch.upper()
    if ch.isalpha():
        return "CHAR_" + ch.upper()
    if ch.isdigit():
        return "CHAR_" + ch
    raise ValueError("未命名的字符: %r (0x%02X) —— 请在 SYMBOL_NAMES 里补一个名字"
                     % (ch, ord(ch)))

added = []
for ch in sorted(NEW):
    code = ord(ch)
    if code in final:
        print("  -- 0x%02X (%r) 已存在，跳过" % (code, ch))
        continue
    name = make_name(ch)
    if any(n == name for n, _ in final.values()):
        name += "_X"
    final[code] = (name, art_to_bits(NEW[ch]))
    added.append((code, name, ch))

print("新增 %d 个: %s" % (len(added), " ".join("%r" % a[2] for a in added)))

